"""Actual native extension ownership/customization admission in disposable consumers."""
from pathlib import Path
import hashlib
import json
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'scripts'), str(ROOT / 'tests')]
import native_phase_ownership as ownership
import validate_phase_refresh as fixture


def snapshot(root):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in root.rglob('*') if p.is_file()}


class NativePhaseOwnershipTests(unittest.TestCase):
    def setUp(self):
        self.fixture = fixture.NativePhaseRefreshTests('test_manual_core_and_preset_customizations_refuse_without_writes')
        self.addCleanup(self.fixture.doCleanups)
        self.fixture.setUp()
        self.root = self.fixture.root

    def test_exact_native_extension_rendering_is_read_only_and_covers_every_registered_output(self):
        before = snapshot(self.root)
        result = ownership.preflight(self.root, ROOT)
        self.assertTrue(result['readOnly'])
        self.assertTrue(result['outputs'])
        self.assertEqual({'program-kit-governance', 'program-kit-building-blocks'},
                         {row['extension'] for row in result['outputs']})
        self.assertIn('program-kit-governance-preset', result['presetSourceSha256'])
        self.assertEqual(before, snapshot(self.root))

    def test_manual_generated_skill_edits_fail_before_any_write(self):
        skill = self.root / '.agents/skills/speckit-program-kit-governance-architecture/SKILL.md'
        skill.write_bytes(skill.read_bytes() + b'\nConsumer authored repair must remain.\n')
        before = snapshot(self.root)
        with self.assertRaisesRegex(ownership.OwnershipError, 'PKU135 consumer customization.*architecture'):
            ownership.preflight(self.root, ROOT)
        self.assertEqual(before, snapshot(self.root))

    def test_independently_edited_installed_source_is_not_authenticated_by_manifest_hash(self):
        source = self.root / '.specify/extensions/program-kit-governance/commands/speckit.program-kit-governance.architecture.md'
        source.write_bytes(source.read_bytes() + b'\nConsumer authored source customization.\n')
        # Native regeneration can make generated bytes agree with customized
        # installed sources. The publisher-source witness still must reject it.
        self.fixture.invoke(['integration', 'use', 'codex'])
        before = snapshot(self.root)
        with self.assertRaisesRegex(ownership.OwnershipError, 'unresolved or customized.*architecture.md'):
            ownership.preflight(self.root, ROOT)
        self.assertEqual(before, snapshot(self.root))

    def test_both_installed_integrations_and_copilot_prompt_customizations_are_admitted_by_exact_bindings(self):
        self.fixture.invoke(['integration', 'install', 'copilot', '--force'])
        self.fixture.invoke(['integration', 'use', 'copilot'])
        before = snapshot(self.root)
        result = ownership.preflight(self.root, ROOT)
        self.assertEqual({'codex', 'copilot'}, {row['integration'] for row in result['outputs']})
        self.assertEqual(before, snapshot(self.root))
        prompts = sorted((self.root / '.github/prompts').glob('speckit.program-kit-governance.*.prompt.md'))
        if prompts:
            selected = prompts[0]
            selected.write_bytes(selected.read_bytes() + b'\nConsumer prompt customization.\n')
            before = snapshot(self.root)
            with self.assertRaisesRegex(ownership.OwnershipError, 'consumer customization.*prompt.md'):
                ownership.preflight(self.root, ROOT)
            self.assertEqual(before, snapshot(self.root))

    def test_unknown_registrations_and_missing_sources_remain_scoped_unresolved(self):
        registry = self.root / '.specify/extensions/.registry'
        data = json.loads(registry.read_text())
        data['extensions']['program-kit-governance']['registered_commands']['codex'].append('speckit.unbound-custom-owner')
        registry.write_text(json.dumps(data))
        before = snapshot(self.root)
        with self.assertRaisesRegex(ownership.OwnershipError, 'no exact current source binding.*program-kit-governance'):
            ownership.preflight(self.root, ROOT)
        self.assertEqual(before, snapshot(self.root))

    def test_preset_template_customization_is_protected_before_replacement(self):
        source = self.root / '.specify/presets/program-kit-governance-preset/templates/tasks-governance.md'
        source.write_bytes(source.read_bytes() + b'\nConsumer task identity policy.\n')
        before = snapshot(self.root)
        with self.assertRaisesRegex(ownership.OwnershipError, 'customized.*program-kit-governance-preset.*tasks-governance.md'):
            ownership.preflight(self.root, ROOT)
        self.assertEqual(before, snapshot(self.root))

    def test_phase_reference_edit_is_not_hidden_by_unchanged_generated_command(self):
        source = self.root / '.specify/extensions/program-kit-governance/references/ui-feedback-and-recovery.md'
        source.write_bytes(source.read_bytes() + b'\nConsumer operation recovery repair.\n')
        before = snapshot(self.root)
        with self.assertRaisesRegex(ownership.OwnershipError, 'customized.*ui-feedback-and-recovery.md'):
            ownership.preflight(self.root, ROOT)
        self.assertEqual(before, snapshot(self.root))

    def test_shipped_catalog_proves_historical_source_without_a_git_checkout_and_rejects_hybrids(self):
        with tempfile.TemporaryDirectory(prefix='native-source-witness-') as name:
            release = Path(name)
            registry = json.loads((self.root / '.specify/extensions/.registry').read_text())
            presets = json.loads((self.root / '.specify/presets/.registry').read_text())
            rows = []
            for kind, entries in (('extensions', registry['extensions']), ('presets', presets['presets'])):
                for identity, metadata in entries.items():
                    if not identity.startswith('program-kit-'):
                        continue
                    installed = self.root / '.specify' / kind / identity
                    files = {relative: ownership.digest((installed / relative).read_bytes()) for relative in ownership.installed_source_files(installed)}
                    rows.append({'kind': kind, 'id': identity, 'version': metadata['version'],
                                 'manifestSha256': metadata['manifest_hash'].removeprefix('sha256:'),
                                 'sourceCommit': 'f' * 40, 'files': files})
            catalog = release / 'extensions/program-kit-governance/references/native-phase-source-baselines.json'
            catalog.parent.mkdir(parents=True)
            catalog.write_text(json.dumps({'schemaVersion': 1, 'components': rows}))
            # Expanded release archives contain generated guides absent from Git
            # source trees. They use the maintained index/hash validator instead.
            import shutil
            from build_release_guidance import build
            validator = release / 'extensions/program-kit-governance/scripts/release_guidance.py'
            validator.parent.mkdir(parents=True)
            shutil.copyfile(ROOT / 'extensions/program-kit-governance/scripts/release_guidance.py', validator)
            for helper in ('render_profile.py', 'asset_sources.py'):
                shutil.copyfile(ROOT / 'extensions/program-kit-governance/scripts' / helper,
                                validator.parent / helper)
            generated = self.root / '.specify/extensions/program-kit-governance/references/release-guidance'
            build(ROOT, generated, (ROOT / 'VERSION').read_text().strip())
            before = snapshot(self.root)
            admitted = ownership.preflight(self.root, release)
            self.assertTrue(admitted['outputs'])
            self.assertEqual('existing-release-guidance-index-validator', admitted['generatedReleaseGuidance']['owner'])
            self.assertEqual(before, snapshot(self.root))
            guide = generated / json.loads((generated / 'migration-index.json').read_text())['entries'][0]['guide']
            original = guide.read_bytes(); guide.write_bytes(original + b'\nModified generated guidance.\n')
            edited = snapshot(self.root)
            with self.assertRaisesRegex(ownership.OwnershipError, 'generated release guidance failed'):
                ownership.preflight(self.root, release)
            self.assertEqual(edited, snapshot(self.root))
            guide.write_bytes(original)
            # Two independently witnessed components cannot authorize an arbitrary
            # hybrid assembled per file from those components.
            governance = next(row for row in rows if row['id'] == 'program-kit-governance')
            altered = json.loads(json.dumps(governance))
            first, second = 'commands/speckit.program-kit-governance.architecture.md', 'scripts/task_draft.py'
            altered['files'][first] = '0' * 64
            governance['files'][second] = '0' * 64
            rows.append(altered)
            catalog.write_text(json.dumps({'schemaVersion': 1, 'components': rows}))
            with self.assertRaisesRegex(ownership.OwnershipError, 'one authenticated original'):
                ownership.preflight(self.root, release)
            self.assertEqual(before, snapshot(self.root))


if __name__ == '__main__':
    unittest.main()
