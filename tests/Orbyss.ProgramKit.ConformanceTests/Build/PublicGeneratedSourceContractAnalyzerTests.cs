    [TestMethod]
    public void EveryCurrentPkcsRuleRemainsExplicitlyPrivate()
    {
        var root = ConformanceInputs.ProgramKitRoot;
        var ledgerPath = Path.Combine(
            root,
            "extensions",
            "reusable-csharp-build-gates",
            "pkcs-private-rule-classification-ledger.json");
        using var ledger = JsonDocument.Parse(File.ReadAllBytes(ledgerPath));
        var classified = ledger.RootElement
            .GetProperty("classificationGroups")
            .EnumerateArray()
            .SelectMany(group => group
                .GetProperty("diagnosticIds")
                .EnumerateArray()
                .Select(item => item.GetString()!))
            .Order(StringComparer.Ordinal)
            .ToArray();
        var sourceFiles = new[]
        {
            Path.Combine(root, "Directory.Build.targets"),
            Path.Combine(
                root,
                "tools",
                "Orbyss.ProgramKit.CSharpGate",
                "Analysis",
                "ProgramKitCSharpGateAnalyzer.cs"),
            Path.Combine(
                root,
                "tools",
                "Orbyss.ProgramKit.CSharpGate",
                "Orbyss.ProgramKit.CSharpGate.csproj"),
        };
        var current = sourceFiles
            .SelectMany(path => Regex.Matches(
                File.ReadAllText(path),
                @"PKCS\d{3}",
                RegexOptions.CultureInvariant)
                .Select(static match => match.Value))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        var groups = ledger.RootElement
            .GetProperty("classificationGroups")
            .EnumerateArray()
            .ToArray();
        var extraction = ledger.RootElement
            .GetProperty("publicResearchExtractions")[0];

        Assert.AreSequenceEqual(current, classified);
        Assert.IsTrue(groups.All(group =>
            group.GetProperty("classification").GetString() ==
                "program-kit-private" &&
            group.GetProperty("ownerId").GetString() ==
                "pkid:domain:program-kit:repository-governance"));
        Assert.AreEqual(
            "PKCS017",
            extraction.GetProperty("privateDiagnosticId").GetString());
        Assert.AreEqual(
            "PKCC001",
            extraction.GetProperty("publicDiagnosticId").GetString());
        Assert.IsTrue(
            extraction.GetProperty("privateRulePreserved").GetBoolean());
        Assert.IsFalse(
            extraction
                .GetProperty("diagnosticMeaningTransferred")
                .GetBoolean());
    }

    [TestMethod]
    public void PublicContractDocumentConformsToItsExactSchema()
    {
        var root = ConformanceInputs.ProgramKitRoot;
        var schemaPath = Path.Combine(
            root,
            "schemas",
            "generated-source-contract",
            "public-generated-source-contract-1.0.0.schema.json");
        var contractPath = Path.Combine(
            root,
            "extensions",
            "reusable-csharp-build-gates",
            "public-generated-source-contract.json");
        var schema = JsonSchema.FromText(File.ReadAllText(schemaPath));
        var contract = JsonDocument.Parse(File.ReadAllBytes(contractPath));
        var result = schema.Evaluate(
            contract.RootElement,
            new EvaluationOptions
            {
                OutputFormat = OutputFormat.List,
            });

        Assert.IsTrue(
            result.IsValid,
            JsonSerializer.Serialize(result));
        Assert.AreEqual(
            "PKCC001",
            contract.RootElement.GetProperty("diagnosticId").GetString());
        Assert.HasCount(
            2,
            contract.RootElement
                .GetProperty("claimsOutsideRule")
                .EnumerateArray());
    }

    [TestMethod]
    public void AnalyzerIsOptInAndProducesExactDiagnosticsAndReceipt()
    {
        var analyzerPath = AnalyzerPath();
        Assert.IsTrue(File.Exists(analyzerPath), analyzerPath);
        using var directory = new PublicAnalyzerTemporaryDirectory();

        var positive = BuildConsumer(
            directory.Create("positive"),
            analyzerPath,
            "ProgramKitGenerated/Feature/Generated.cs",
            """
            // <auto-generated program-kit>
            namespace Consumer;
            public sealed class Generated;
            """,
            optIn: true);
        var negative = BuildConsumer(
            directory.Create("negative"),
            analyzerPath,
            "Physical.cs",
            """
            // <auto-generated program-kit>
            namespace Consumer;
            public sealed class Physical;
            """,
            optIn: true);
        var unrelated = BuildConsumer(
            directory.Create("unrelated"),
            analyzerPath,
            "Physical.cs",
            """
            // <auto-generated program-kit>
            namespace Consumer;
            public sealed class Physical;
            """,
            optIn: false);
        var suppressed = BuildConsumer(
            directory.Create("suppressed"),
            analyzerPath,
            "ProgramKitGenerated/Feature/Suppressed.cs",
            """
            #pragma warning disable PKCC001
            namespace Consumer;
            public sealed class Suppressed;
            """,
            optIn: true);

        Assert.AreEqual(0, positive.ExitCode, positive.Output);
        Assert.IsGreaterThan(0, negative.ExitCode, negative.Output);
        Assert.Contains("PKCC001", negative.Output);
        Assert.AreEqual(0, unrelated.ExitCode, unrelated.Output);
        Assert.DoesNotContain("PKCC001", unrelated.Output);
        Assert.AreEqual(0, suppressed.ExitCode, suppressed.Output);
        Assert.DoesNotContain("PKCS", string.Concat(
            positive.Output,
            negative.Output,
            unrelated.Output,
            suppressed.Output));
        Assert.IsLessThanOrEqualTo(
            30000L,
            positive.ElapsedMilliseconds,
            "Focused public-analyzer build exceeded its contract budget.");

        var receipt = Directory
            .EnumerateFiles(
                positive.ProjectDirectory,
                "GeneratedSourceContractReceipt.*.cs",
                SearchOption.AllDirectories)
            .Single();
        Assert.Contains(
            string.Concat(
                "// public-analyzer-receipt:generated-source-contract:",
                Nonce),
            File.ReadAllText(receipt));
    }

    [TestMethod]
    public void PackageContainsOnlyAnalyzerContractSchemaAndDocumentation()
    {
        using var directory = new PublicAnalyzerTemporaryDirectory();
        var output = directory.Create("package");
        var project = Path.Combine(
            ConformanceInputs.ProgramKitRoot,
            "src",
            "Orbyss.ProgramKit.GeneratedSourceContract.Analyzers",
            "Orbyss.ProgramKit.GeneratedSourceContract.Analyzers.csproj");
        var pack = Run(
            ConformanceInputs.ProgramKitRoot,
            "pack",
            project,
            "--configuration",
            "Release",
            "--no-restore",
            "--output",
            output);

        Assert.AreEqual(0, pack.ExitCode, pack.Output);
        var package = Directory
            .EnumerateFiles(output, "*.nupkg")
            .Single(path => !path.EndsWith(".snupkg", StringComparison.Ordinal));
        using var archive = ZipFile.OpenRead(package);
        var entries = archive.Entries
            .Select(static entry => entry.FullName)
            .Order(StringComparer.Ordinal)
            .ToArray();
        var manifestPath = Path.Combine(
            ConformanceInputs.ProgramKitRoot,
            "extensions",
            "reusable-csharp-build-gates",
            "public-generated-source-analyzer-manifest.json");
        using var manifest = JsonDocument.Parse(
            File.ReadAllBytes(manifestPath));
        var requiredAssets = manifest.RootElement
            .GetProperty("requiredPackageAssets")
            .EnumerateArray()
            .Select(static item => item.GetString()!)
            .ToArray();

        foreach (var asset in requiredAssets)
        {
            Assert.Contains(asset, entries);
        }
        Assert.DoesNotContain(static entry =>
            entry.StartsWith("lib/", StringComparison.OrdinalIgnoreCase) ||
            entry.StartsWith("ref/", StringComparison.OrdinalIgnoreCase) ||
            entry.StartsWith("runtimes/", StringComparison.OrdinalIgnoreCase) ||
            entry.StartsWith("build/", StringComparison.OrdinalIgnoreCase) ||
            entry.StartsWith(
                "buildTransitive/",
                StringComparison.OrdinalIgnoreCase),
            entries);
        var nuspecEntry = archive.Entries.Single(static entry =>
            entry.FullName.EndsWith(".nuspec", StringComparison.Ordinal));
        using var reader = new StreamReader(nuspecEntry.Open(), Encoding.UTF8);
        var nuspec = reader.ReadToEnd();
        Assert.DoesNotContain("<dependency ", nuspec);

        foreach (var input in manifest.RootElement
                     .GetProperty("sourceInputs")
                     .EnumerateArray())
        {
            var path = Path.Combine(
                ConformanceInputs.ProgramKitRoot,
                input.GetProperty("path").GetString()!
                    .Replace('/', Path.DirectorySeparatorChar));
            var actual = string.Concat(
                "sha256:",
                Convert.ToHexStringLower(
                    SHA256.HashData(File.ReadAllBytes(path))));
            Assert.AreEqual(
                input.GetProperty("digest").GetString(),
                actual,
                path);
        }

        var manifestDigest = string.Concat(
            "sha256:",
            Convert.ToHexStringLower(
                SHA256.HashData(File.ReadAllBytes(manifestPath))));
        using var versionMap = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(
            ConformanceInputs.ProgramKitRoot,
            "extensions",
            "reusable-csharp-build-gates",
            "public-generated-source-contract-version-map.json")));
        var packageAndImplementation = versionMap.RootElement
            .GetProperty("nodes")
            .EnumerateArray()
            .Where(node =>
                node.GetProperty("kind").GetString() is
                    "package" or "implementation")
            .ToArray();
        Assert.HasCount(2, packageAndImplementation);
        Assert.IsTrue(packageAndImplementation.All(node =>
            node.GetProperty("revision")
                .GetProperty("digest")
                .GetString() == manifestDigest));
    }

    private static string AnalyzerPath() =>
        Path.Combine(
            ConformanceInputs.ProgramKitRoot,
            "src",
            "Orbyss.ProgramKit.GeneratedSourceContract.Analyzers",
            "bin",
            "Debug",
            "net10.0",
            "Orbyss.ProgramKit.GeneratedSourceContract.Analyzers.dll");

    private static PublicAnalyzerBuildResult BuildConsumer(
        string projectDirectory,
        string analyzerPath,
        string sourcePath,
        string source,
        bool optIn)
    {
        var projectPath = Path.Combine(projectDirectory, "Consumer.csproj");
        var absoluteSourcePath = Path.Combine(
            projectDirectory,
            sourcePath.Replace('/', Path.DirectorySeparatorChar));
        Directory.CreateDirectory(
            Path.GetDirectoryName(absoluteSourcePath)!);
        File.WriteAllText(absoluteSourcePath, source, Encoding.UTF8);
        var activation = optIn
            ? """
                <ProgramKitGeneratedSourceContract>1.0.0</ProgramKitGeneratedSourceContract>
                <ProgramKitPublicAnalyzerReceiptNonce>0123456789abcdef0123456789abcdef</ProgramKitPublicAnalyzerReceiptNonce>
              """
            : string.Empty;
        File.WriteAllText(
            projectPath,
            $$"""
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <Nullable>enable</Nullable>
                <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
                <EmitCompilerGeneratedFiles>true</EmitCompilerGeneratedFiles>
                <CompilerGeneratedFilesOutputPath>GeneratedOutput</CompilerGeneratedFilesOutputPath>
            {{activation}}
              </PropertyGroup>
              <ItemGroup>
                <Analyzer Include="{{SecurityElement.Escape(analyzerPath)}}" />
                <CompilerVisibleProperty Include="ProgramKitGeneratedSourceContract" />
                <CompilerVisibleProperty Include="ProgramKitPublicAnalyzerReceiptNonce" />
              </ItemGroup>
            </Project>
            """,
            Encoding.UTF8);

        var result = Run(
            projectDirectory,
            "build",
            projectPath,
            "--configuration",
            "Release",
            "--nologo",
            "--property:UseSharedCompilation=false");
        return new PublicAnalyzerBuildResult(
            result.ExitCode,
            result.Output,
            result.ElapsedMilliseconds,
            projectDirectory);
    }

    private static PublicAnalyzerBuildResult Run(
        string workingDirectory,
        params string[] arguments)
    {
        ProcessStartInfo startInfo = new("dotnet")
        {
            WorkingDirectory = workingDirectory,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true,
        };
        foreach (var argument in arguments)
        {
            startInfo.ArgumentList.Add(argument);
        }

        var stopwatch = Stopwatch.StartNew();
        using var process = Process.Start(startInfo)
            ?? throw new InvalidOperationException("Unable to start dotnet.");
        var output = process.StandardOutput.ReadToEndAsync();
        var error = process.StandardError.ReadToEndAsync();
        if (!process.WaitForExit(60000))
        {
            process.Kill(entireProcessTree: true);
            throw new TimeoutException(
                "The public analyzer fixture exceeded 60 seconds.");
        }

        Task.WaitAll(output, error);
        stopwatch.Stop();
        return new PublicAnalyzerBuildResult(
            process.ExitCode,
            string.Concat(output.Result, error.Result),
            stopwatch.ElapsedMilliseconds,
            workingDirectory);
    }
