"""Infer scoped feature mechanisms from ordinary design and engineering inputs."""
from pathlib import Path
import json
import re

CAPABILITIES = {
    'dotnet': r'(?<!\w)(?:c#|asp\.net(?:\s+core)?|\.net|dotnet)(?!\w)',
    'web': r'\b(?:browser|frontend|react|vite|typescript)\b',
    'api': r'\b(?:http|openapi|endpoint|api)\b',
    'persistence': r'\b(?:persistence|database|dbcontext|postgresql|sqlserver|sqlite|entityframeworkcore|entity framework|npgsql)\b',
    'capabilities': r'\b(?:capability|building.block|shellfeature|composition|activation)\b',
    'typescript': r'\btypescript\b',
    'identity-admin': r'\b(?:keycloak admin|identity administration|realm provisioning|admin rest)\b',
    'domain-events': r'\b(?:idomainevent(?:publisher|handler)?|independent domain.event reactions)\b',
    'file-selection': r'\b(?:filereader|file.selection generations?)\b',
    'resource-fencing': r'\b(?:resource.side fencing|physical (?:publish|erase) fencing)\b',
    'pdf-decoding': r'\b(?:pdfpig|flatedecode|finite pdf decod(?:er|ing))\b',
    'recording-ocr': r'\b(?:recording.only ocr|offline ocr sdk)\b',
    'snapshot-query': r'\bimmutable snapshot quer(?:y|ies)\b',
    'browser-effects': r'\b(?:async|await|promise|settimeout|setinterval|queuemicrotask|requestanimationframe|abortcontroller|abortsignal|arraybuffer|filereader|getdocument|fetch|websocket|worker|createobjecturl)\b|\.then\s*\(',
}

# Existing task-reference source formats; this is ownership, not language analysis.
CODE_SOURCE_SUFFIXES = {'.cs', '.ts', '.tsx', '.js', '.jsx', '.py', '.rs', '.go', '.java', '.kt', '.cpp', '.h', '.c', '.sql', '.html', '.css'}


FRONTEND_EXCLUDED_PARTS = {'.git', '.specify', '.program-kit', '.codex', '.agents', '.aws', '.ssh', 'artifacts', 'node_modules', 'vendor', 'dist', 'obj', 'bin'}


def task_sources(root, tasks):
    """Explicit authored task owners support manual/nonnative engineering routes.

    A request's affected-path hints do not establish ownership. Actual checklist
    source references are confined and hashed alongside evaluated native owners.
    """
    root = root.resolve()
    text = '\n'.join(tasks)
    candidates = set(re.findall(r'(?<![\w:])((?:[\w.-]+/)+[\w.-]+\.[\w]+)', text))
    candidates.update(re.findall(r'(?<![\w/.-])([\w.-]+\.(?:cs|tsx?|jsx?|py|rs|go|java|kt|cpp|h|c|sql|txt|md|json|xml|csproj|props|targets|yml|yaml|html|css))(?![\w/.-])', text))
    result = []
    for relative in sorted(candidates):
        path = (root / relative).resolve()
        if (not path.is_relative_to(root) or FRONTEND_EXCLUDED_PARTS.intersection(path.relative_to(root).parts)
                or not path.is_file() or re.search(r'\.(?:g|generated)\.[^.]+$', path.name, re.I)):
            continue
        result.append(path)
    return result


def frontend_sources(root, package):
    """One authored-source scope for context, inspection and conformance recovery."""
    root, directory = root.resolve(), package.parent.resolve()
    if not directory.is_relative_to(root):
        return []
    result = []
    for path in directory.rglob('*'):
        if (path.suffix not in ('.ts', '.tsx', '.js', '.jsx', '.css', '.html')
                or FRONTEND_EXCLUDED_PARTS.intersection(path.relative_to(root).parts)
                or not path.resolve().is_relative_to(root) or not path.is_file()):
            continue
        if re.search(r'\.(?:g|generated)\.[^.]+$', path.name, re.I):
            continue
        owner = path.parent
        nested_owner = False
        while owner != directory:
            if (owner / 'package.json').is_file():
                nested_owner = True
                break
            owner = owner.parent
        if nested_owner:
            continue
        if '<auto-generated' in path.read_text(encoding='utf-8')[:1024].lower():
            continue
        result.append(path)
    return sorted(result)


def frontend_packages(root, prose, affected_paths=()):
    """Select nearest actual package owners from explicit scoped frontend paths."""
    root = root.resolve()
    found = set()
    candidates = set(re.findall(r'(?<![\w:])((?:[\w.-]+/)+[\w.-]+)', prose)) | set(affected_paths)
    candidates.update(re.findall(r'(?<![\w/.-])([\w.-]+\.(?:tsx?|jsx?)|package\.json)(?![\w/.-])', prose))
    for relative in candidates:
        path = (root / relative).resolve()
        if not path.is_relative_to(root) or FRONTEND_EXCLUDED_PARTS.intersection(path.relative_to(root).parts):
            continue
        if path.is_dir():
            if (path / 'package.json').is_file():
                found.add(path / 'package.json')
            continue
        if path.name != 'package.json' and path.suffix not in ('.ts', '.tsx', '.js', '.jsx', '.css', '.html'):
            continue
        path = path.parent
        while path.is_relative_to(root):
            if (path / 'package.json').is_file():
                found.add(path / 'package.json')
                break
            if path == root:
                break
            path = path.parent
    return sorted(found)


def feature_scope(root, feature):
    """Resolve existing feature identity, without promoting a draft or changing intake."""
    from specification_intake import spec_entries, resolve_spec_brief
    spec = feature / 'spec.md'
    entries = spec_entries(spec.read_text(encoding='utf-8')) if spec.is_file() else []
    if len(entries) > 1:
        raise ValueError('Feature must identify exactly one specification roadmap entry')
    entry = entries[0] if entries else None
    path, brief = resolve_spec_brief(root, spec)
    scope = brief.get('architectureScope')
    from feature_knowledge import project
    projection = project(root, scope, feature_id=brief.get('featureId')) if scope is not None else None
    return {'entry': entry, 'featureId': brief.get('featureId'), 'brief': brief, 'briefPath': path, 'projection': projection}


def adopted_context(root, feature, selected_paths=()):
    """Join feature ownership to selected targets; never inherit every repository capability."""
    scoped = feature_scope(root, feature)
    projection = scoped['projection']
    if projection is None:
        diagnostics = ['No explicit architecture scope is available; guidance uses feature prose and selected files. '
                       'Resolve ownership before adopting a target.'] if scoped['entry'] else []
        return {'tags': set(), 'sources': [], 'diagnostics': diagnostics}
    elements = projection['elements']
    selected = set(projection['scope'])
    # Parent context ownership is applicable. Neighboring contracts are knowledge,
    # not authority to activate those neighbors' private implementations.
    all_elements = {e['id']: e for e in elements}
    relevant = set(selected)
    while True:
        expanded = relevant | {e['id'] for e in elements if e.get('parent') in relevant}
        if expanded == relevant:
            break
        relevant = expanded
    owned_targets = set(relevant)
    while True:
        parents = {all_elements[i]['parent'] for i in relevant if i in all_elements
                   and all_elements[i].get('parent') in all_elements}
        if parents <= relevant:
            break
        relevant |= parents
    referenced = {d for i in owned_targets for d in all_elements.get(i, {}).get('decision_refs', [])}
    decisions = {d['id'] for d in projection['decisions'] if d['id'] in referenced
                 and d.get('status', '').lower() == 'accepted'
                 and d['id'] != 'bootstrap-baseline'}
    selection_path = root / 'docs/architecture/building-block-selection.json'
    selection = json.loads(selection_path.read_text(encoding='utf-8')) if selection_path.is_file() else {}
    targets, diagnostics = {}, []
    for target in selection.get('targets', []):
        placement = target.get('placement', {})
        owner = placement.get('owner')
        decision_match = decisions.intersection(placement.get('decisionIds', []))
        if owner in owned_targets or decision_match and (owner in relevant or owner is None):
            targets[target['id']] = target
        elif decision_match:
            diagnostics.append('Target ' + target['id'] + ' cites a scoped decision but belongs to another owner; '
                               'resolve placement before adopting its private capabilities.')
        elif owner in relevant:
            diagnostics.append('Target ' + target['id'] + ' belongs to a broader ancestor; '
                               'identify its applicability to this feature before inheriting capabilities.')
    if selected_paths:
        # Reuse actual source/package/project ownership, not a feature-wide
        # profile union. A target without a path remains explicitly unknown.
        selected_paths = {str(p).replace('\\', '/') for p in selected_paths}
        def selected_target(target):
            relative = target.get('path')
            if not isinstance(relative, str) or not relative:
                return True
            relative = relative.replace('\\', '/')
            path = Path(relative)
            owner = path.parent.as_posix() if path.suffix else path.as_posix()
            return any(p == relative or p.startswith(owner + '/') for p in selected_paths)
        targets = {identity: target for identity, target in targets.items() if selected_target(target)}
    tags, sources = set(), []
    if targets:
        sources.append({'path': 'docs/architecture/building-block-selection.json',
                        'status': selection.get('status', 'Draft'), 'targets': sorted(targets),
                        'targetPaths': sorted(t['path'] for t in targets.values() if t.get('path'))})
        if selection.get('status') != 'Accepted':
            diagnostics.append('Scoped targets are proposed: design guidance does not establish adoption or compatibility.')
    compositions = {
        'api_baseline': {'dotnet', 'api', 'capabilities'},
        'browser_bff': {'dotnet', 'api', 'web', 'capabilities'},
        'browser_spa_pkce': {'dotnet', 'api', 'web', 'capabilities'},
        'identity_administration': {'dotnet', 'identity-admin', 'capabilities'},
        'service_to_service': {'dotnet', 'capabilities'},
        'hosted_pages': {'dotnet', 'api', 'web', 'capabilities'},
        'persistence': {'dotnet', 'persistence', 'capabilities'},
    }
    for target in targets.values():
        if target.get('kind') == 'dotnet-project':
            tags.add('dotnet')
    for instance in selection.get('instances', []):
        bound_targets = {
            target_id
            for binding in instance.get('targetBindings', {}).values()
            for target_id in (binding if isinstance(binding, list) else [binding])
            if isinstance(target_id, str)
        }
        if bound_targets.intersection(targets):
            tags.update(compositions.get(instance.get('composition'), set()))
            if instance.get('composition') not in compositions:
                diagnostics.append('Unmapped selected composition ' + str(instance.get('composition'))
                                   + ': resolve its responsibilities and technology before design.')
    # Technology belongs to the selected domain/module, not an unrelated root SDK.
    technology_owners = {target.get('placement', {}).get('owner') for target in targets.values()} if selected_paths and targets else relevant
    for identity in technology_owners:
        element = all_elements.get(identity, {})
        if identity not in selected and element.get('type') == 'software-system':
            continue
        technology = element.get('technology', '').lower()
        tags.update(tag for tag, pattern in CAPABILITIES.items() if re.search(pattern, technology))
    # Profile facets come only from the accepted owned projection above. A root
    # profile or an unrelated instance never narrows another feature's duties.
    if targets and selection.get('status') == 'Accepted':
        for instance in selection.get('instances', []):
            bound = {i for value in instance.get('targetBindings', {}).values()
                     for i in (value if isinstance(value, list) else [value]) if isinstance(i, str)}
            if bound.intersection(targets):
                profile = {'browser_bff': 'bff-cookie-v1', 'browser_spa_pkce': 'spa-pkce-v1',
                           'service_to_service': 'service_to_service'}.get(instance.get('composition'))
                if profile:
                    tags.add('secure-web:' + profile)
    return {'tags': tags, 'sources': sources, 'diagnostics': diagnostics}
MECHANISMS = {
    'async': r'\b(?:async|await|task|valuetask|cancellation|deadline)\b',
    'concurrency': r'\b(?:concurrency|concurrent|parallel|lock|semaphore|shared state|channel|queue|contention)\b',
    'lifetime': r'\b(?:disposal|dispose|idisposable|iasyncdisposable|lifetime|scope|lease|factory|dependency injection|di)\b',
    'queries': r'\b(?:linq|query|queries|pagination|paging|iqueryable|enumeration)\b',
    'io': r'\b(?:i/o|io|httpclient|file|stream|timeout|deadline|options|configuration)\b',
    'security': r'\b(?:authorization|authentication|identity|secret|untrusted|security|permission|process|url|path admission)\b',
}


def responsibility_tags():
    """Vocabulary supplied by this detector, not a second extension registry."""
    return {'project-role:' + role for role in ('core', 'helper', 'implementation', 'provider', 'bridge', 'test')} | set(CAPABILITIES) | {'all', 'http-api', 'source-production', 'evaluated-dotnet',
        'secure-web:bff-cookie-v1', 'secure-web:spa-pkce-v1', 'secure-web:none-v1', 'secure-web:service_to_service',
        'dotnet-host:foundation', 'dotnet-host:conventional'} | {'dotnet-' + name for name in MECHANISMS}


def rule_applicable(rule, tags):
    """One selector for accepted facts; missing profile facts stay conservative."""
    tags = set(tags)
    when = rule.get('when', {})
    if (set(when.get('all', [])) - tags or set(when.get('not', [])) & tags
            or when.get('any') and not set(when['any']) & tags):
        return False
    for dimension, allowed in rule.get('profileScope', {}).items():
        selected = {tag.split(':', 1)[1] for tag in tags if tag.startswith(dimension + ':')}
        if selected and not selected.intersection(allowed):
            return False
    return True


def applicable_requirements(catalog, tags, phase='implementation'):
    """One applicability owner for guidance, pre-code decisions and review duties."""
    tags = set(tags) | {'all'}
    registry_phase = 'after-plan' if phase == 'tasks' else phase
    return [{**row, 'ruleIds': [identity for identity in row.get('ruleIds', [])
                               if rule_applicable(catalog['rules'][identity], tags)],
             'selectionTags': sorted(tags)} for row in catalog['requirements']
            if row['when'] in tags and registry_phase in row['phases']
            and (not row.get('mechanism') or row['mechanism'] in tags)]


def affirmative(text):
    """Exclude explicit non-goals from prose inference, never actual package evidence."""
    # Retained task/approval history is not current affirmative feature intent.
    # These are ordinary optional Markdown labels, not a required plan protocol.
    PLAN_COLUMNS = ['Operation', 'Decision', 'Resolution', 'Source']
    DECISIONS = {'ownership', 'results', 'limits', 'cancellation-deadline', 'cleanup-uncertainty',
                 'transactions-replay', 'admission', 'bounds', 'concurrency', 'configuration-time', 'activation-drain'}
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    excluded_depth = None
    lines = []
    decision_table = False
    for line in text.splitlines():
        if line.lstrip().startswith('|'):
            cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
            if cells == PLAN_COLUMNS:
                decision_table = True
                continue
            if decision_table and len(cells) == 4:
                if all(re.fullmatch(r':?-+:?', cell) for cell in cells):
                    continue
                # Canonical decision keys name responsibilities to assess, not
                # mechanisms the operation implements. Only authored affirmative
                # resolutions supply intent; actual native/source facts stay due.
                if cells[1] in DECISIONS:
                    if re.match(r'Not applicable\b', cells[2], re.I):
                        continue
                    line = cells[2] + ' ' + cells[3]
            elif decision_table:
                decision_table = False
        else:
            decision_table = False
        heading = re.match(r'^\s*(#+)\s', line)
        # Native task-plan headings/table labels describe workflow, not Task/async usage.
        # Keep real task descriptions and source untouched, including Task<T> code.
        if heading:
            line = re.sub(r'\btasks?\b', '', line, flags=re.I)
        if re.match(r'^\s*\|\s*Task\s*\|', line, re.I):
            continue
        if heading:
            depth = len(heading[1])
            if excluded_depth is not None and depth <= excluded_depth:
                excluded_depth = None
            if re.search(r'non.?goals?|out of scope|excluded|future work', line, re.I):
                excluded_depth = depth
        if excluded_depth is None:
            lines.append(line)
    clauses = re.split(r'(?<=[.!?;])\s+|\n', '\n'.join(lines))
    result = []
    for clause in clauses:
        # Preserve an affirmative prefix in "API without database" while dropping
        # clauses such as "API and browser are out of scope" altogether.
        if re.search(r'\b(?:out of scope|not required|excluded|future|deferred)\b', clause, re.I):
            continue
        result.append(re.split(r'\b(?:no|without)\s', clause, maxsplit=1, flags=re.I)[0])
    return '\n'.join(result)


def frontend_only_declaration(prose):
    """A negated layer split is not an affirmative frontend-only scope."""
    for match in re.finditer(r'\b(?:frontend|browser|ui)[ -]only\b', prose, re.I):
        prefix = re.split(r'[.!?;\n]', prose[:match.start()])[-1]
        if not re.search(r'\b(?:not|never|no)\b[^.!?;\n]{0,120}$', prefix, re.I):
            return True
    return False


def context(root, feature, phase, affected_paths=(), prose_override=None, actual_source=None,
            include_inherited=True, inherited_runtime=True):
    prose = '\n'.join(affirmative(path.read_text(encoding='utf-8'))
                      for name in ('spec.md', 'plan.md', 'research.md', 'data-model.md', 'quickstart.md', 'tasks.md')
                      if (path := feature / name).is_file())
    if prose_override is not None:
        prose = affirmative(prose_override)
    projects = [p for p in (root / 'src').rglob('*.csproj') if not {'bin', 'obj'} & set(p.parts)]
    projects += [p for p in feature.rglob('*.csproj') if not {'bin', 'obj'} & set(p.parts)]
    selected = [p for p in set(projects) if p.relative_to(root).as_posix() in prose
                or p.parent.relative_to(root).as_posix() in prose
                or any(str(item).replace('\\', '/') == p.relative_to(root).as_posix()
                       or str(item).replace('\\', '/').startswith(p.parent.relative_to(root).as_posix() + '/')
                       for item in affected_paths)]
    engineering, source = [], []
    for project in selected:
        engineering.append(project.read_text(encoding='utf-8'))
        if phase in ('implementation', 'delivery'):
            for path in project.parent.rglob('*.cs'):
                if {'bin', 'obj'} & set(path.parts):
                    continue
                if not affected_paths or any(path.relative_to(root).as_posix() == p or
                    path.relative_to(root).as_posix().startswith(p.rstrip('/') + '/') for p in affected_paths):
                    source.append(path.read_text(encoding='utf-8'))
    for package in frontend_packages(root, prose, affected_paths):
        engineering.append(package.read_text(encoding='utf-8'))
        if phase in ('implementation', 'delivery'):
            for path in frontend_sources(root, package):
                if path.suffix in ('.ts', '.tsx', '.js', '.jsx'):
                    source.append(path.read_text(encoding='utf-8'))
    if actual_source is not None:
        source = actual_source
    content = '\n'.join([prose, *engineering, *source]).lower()
    selected_paths = {*affected_paths, *(p.relative_to(root).as_posix() for p in selected),
                      *(p.relative_to(root).as_posix() for p in frontend_packages(root, prose, affected_paths))}
    inherited = adopted_context(root, feature, selected_paths) if include_inherited else {'tags': set()}
    frontend_only = frontend_only_declaration(prose)
    if frontend_only and selected:
        raise ValueError('A frontend-only declaration conflicts with selected backend project evidence; resolve the feature scope')
    inherited_tags = inherited['tags'] - ({'dotnet', 'api', 'persistence', 'capabilities'} if frontend_only else set())
    # Accepted domain technology describes design knowledge, not source effects.
    # Only an evaluated all-Core/helper owner scope may omit inherited runtime
    # signals; actual project/source evidence below always remains additive.
    if not inherited_runtime:
        inherited_tags -= {'persistence', 'api'}
    tags = {'all'} | inherited_tags
    tags.update(tag for tag, pattern in CAPABILITIES.items() if re.search(pattern, content))
    identity = r'\b(?:sign[ -]?in|sign[ -]?out|login|logout|password[ -]reset|account[ -]recovery|credential[ -]recovery)\b'
    presentation = r'\b(?:screens?|pages?|forms?|styling|accessibility)\b'
    # User-visible identity screens need UI guidance before frontend source exists.
    # A backend/CLI login operation alone does not establish a browser surface.
    if re.search(identity + r'[^\n]{0,100}' + presentation + '|' + presentation + r'[^\n]{0,100}' + identity, prose, re.I):
        tags.add('web')
    if selected:
        tags.add('dotnet')
    packages = '\n'.join(engineering).lower()
    # Qualified identity is stronger evidence than wording in the plan.
    if any(name in packages for name in ('entityframeworkcore', 'npgsql', 'microsoft.data.sqlite', 'microsoft.data.sqlclient')):
        tags.add('persistence')
    if 'microsoft.aspnetcore' in packages or 'microsoft.net.sdk.web' in packages:
        tags.add('api')
    if any(name in packages for name in ('"vite"', '"react"', '"typescript"')):
        tags.add('web')
    if '"typescript"' in packages:
        tags.add('typescript')
    if 'api' in tags:
        tags.add('http-api')
    mechanisms = {name for name, pattern in MECHANISMS.items() if re.search(pattern, content)}
    if tags & {'persistence', 'api'}:
        mechanisms.update(('async', 'lifetime', 'io', 'security'))
    if 'persistence' in tags:
        mechanisms.update(('queries', 'concurrency'))
    if 'capabilities' in tags:
        mechanisms.add('lifetime')
    tags.update('dotnet-' + name for name in mechanisms if 'dotnet' in tags)
    return tags


def markdown_table(content, heading, width):
    """Read an optional ordinary task table without coding/delivery state."""
    from knowledge_sources import markdown_headings
    headings = markdown_headings(content)
    start = next((index for index, _, title in headings if title == heading), None)
    if start is None:
        return []
    end = next((index for index, _, _ in headings if index > start), len(content.splitlines()))
    rows = []
    for line in content.splitlines()[start + 1:end]:
        if not line.strip().startswith('|'):
            continue
        cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
        if len(cells) != width:
            raise ValueError('Malformed optional task table: ' + heading)
        if all(re.fullmatch(r':?-+:?', cell) for cell in cells):
            continue
        rows.append(cells)
    return rows[1:] if rows else []


def task_scope(feature, operation=None, task_ids=None, feature_wide=False):
    """Optional recipe scope from visible task IDs/table, never hidden checkpoints."""
    content = (feature / 'tasks.md').read_text(encoding='utf-8') if (feature / 'tasks.md').is_file() else ''
    tasks = [line for line in content.splitlines() if re.match(r'^\s*- \[[ xX]\] T\d+\b', line)]
    all_ids = set(re.findall(r'^\s*- \[[ xX]\] (T\d+)\b', content, re.M))
    operation = None if task_ids is not None or feature_wide else operation
    # Explicit callers can select an operation only when its authored mapping exists.
    ids = {row[0] for row in markdown_table(content, 'Task dependency map', 5) if row[1] == operation} if operation else all_ids
    if operation and not ids:
        raise ValueError('Unknown operation in the optional Task dependency map: ' + operation)
    if task_ids is not None:
        ids = set(task_ids)
        if not ids <= all_ids:
            raise ValueError('Recipe scope names unknown task IDs')
    selected = [line for line in tasks if any(re.match(r'^\s*- \[[ xX]\] ' + re.escape(identity) + r'\b', line) for identity in ids)]
    return {'operation': operation, 'taskIds': sorted(ids), 'tasks': selected,
            'baseline': None, 'mode': 'tasks' if task_ids is not None else 'operation' if operation else 'feature'}
