"""Export owner-authored pure label rules and generate matching browser admission.

This deliberately supports one closed contract: reject raw C0/C1 controls, trim
the exact .NET whitespace set, then admit UTF-16 length. It does not infer policy
from arbitrary C# methods or use JSON Schema maxLength for normalized input.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys


TRIM_CODE_UNITS = [9, 10, 11, 12, 13, 32, 133, 160, 5760, *range(8192, 8203), 8232, 8233, 8239, 8287, 12288]
RAW_CONTROL_RANGES = [[0, 31], [127, 159]]
ORDER = ['rejectRawControls', 'trim', 'validateUtf16Length']
MAX_DESCRIPTOR_BYTES = 262_144
IDENTITY = re.compile(r'[A-Za-z][A-Za-z0-9_.:-]{0,127}\Z')


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError('PKV001 ' + message)


def positive_integer(value: object) -> bool:
    return type(value) is int and 1 <= value <= 2_147_483_647


def validate_descriptor(value: object) -> dict:
    require(isinstance(value, dict), 'descriptor must be an object')
    require(set(value) == {'schemaVersion', 'owner', 'contractId', 'contractVersion', 'rules'}, 'unsupported descriptor fields')
    require(type(value['schemaVersion']) is int and value['schemaVersion'] == 1, 'unsupported schemaVersion')
    for key in ('owner', 'contractId'):
        require(isinstance(value[key], str) and IDENTITY.fullmatch(value[key]) is not None, 'invalid ' + key)
    require(positive_integer(value['contractVersion']), 'invalid contractVersion')
    rules = value['rules']
    require(isinstance(rules, dict) and 1 <= len(rules) <= 64, 'rules must contain 1-64 owned entries')
    identities = set()
    for name, rule in rules.items():
        require(isinstance(name, str) and IDENTITY.fullmatch(name) is not None, 'invalid rule key')
        require(isinstance(rule, dict) and set(rule) == {'ruleId', 'ruleVersion', 'normalizationOrder', 'trimCodeUnits',
            'rejectedRawCodeUnitRanges', 'lengthUnit', 'minimumLength', 'maximumLength'}, 'unsupported rule fields: ' + name)
        require(isinstance(rule['ruleId'], str) and IDENTITY.fullmatch(rule['ruleId']) is not None, 'invalid ruleId: ' + name)
        require(rule['ruleId'] not in identities, 'duplicate ruleId')
        identities.add(rule['ruleId'])
        require(positive_integer(rule['ruleVersion']), 'invalid ruleVersion')
        require(rule['normalizationOrder'] == ORDER, 'unsupported normalization order')
        require(rule['lengthUnit'] == 'utf16', 'unsupported length unit')
        require(rule['trimCodeUnits'] == TRIM_CODE_UNITS and all(type(unit) is int for unit in rule['trimCodeUnits']), 'unsupported trim set')
        require(rule['rejectedRawCodeUnitRanges'] == RAW_CONTROL_RANGES
            and all(type(unit) is int for pair in rule['rejectedRawCodeUnitRanges'] for unit in pair), 'unsupported raw control set')
        require(positive_integer(rule['minimumLength']) and positive_integer(rule['maximumLength'])
            and rule['minimumLength'] <= rule['maximumLength'], 'invalid normalized length bounds')
    return value


def canonical_bytes(value: dict) -> bytes:
    return (json.dumps(validate_descriptor(value), ensure_ascii=True, indent=2, sort_keys=True) + '\n').encode('utf-8')


def unique_object_pairs(pairs: list[tuple[str, object]]) -> dict:
    value = {}
    for key, item in pairs:
        require(key not in value, 'duplicate JSON property: ' + key)
        value[key] = item
    return value


def parse_descriptor(data: str) -> dict:
    return validate_descriptor(json.loads(data, object_pairs_hook=unique_object_pairs))


def read_descriptor(path: Path) -> dict:
    data = path.read_bytes()
    require(len(data) <= MAX_DESCRIPTOR_BYTES, 'descriptor exceeds byte bound')
    return parse_descriptor(data.decode('utf-8-sig'))


def generate_typescript(descriptor: dict) -> bytes:
    digest = hashlib.sha256(canonical_bytes(descriptor)).hexdigest()
    metadata = json.dumps(descriptor, ensure_ascii=True, indent=2, sort_keys=True)
    source = '''// Generated by Program Kit label_validation.py; edit the owner rule and re-export.
// Raw values remain caller-owned. This function never truncates or changes the input control.
export const validationDescriptorSha256 = DIGEST;
export const labelValidationMetadata = METADATA as const;
for (const rule of Object.values(labelValidationMetadata.rules)) {
  Object.freeze(rule.normalizationOrder);
  Object.freeze(rule.trimCodeUnits);
  for (const range of rule.rejectedRawCodeUnitRanges) Object.freeze(range);
  Object.freeze(rule.rejectedRawCodeUnitRanges);
  Object.freeze(rule);
}
Object.freeze(labelValidationMetadata.rules);
Object.freeze(labelValidationMetadata);
export type LabelRuleName = keyof typeof labelValidationMetadata.rules;
export type LabelValidationResult =
  | { readonly valid: true; readonly value: string }
  | { readonly valid: false; readonly error: {
      readonly code: 'type' | 'control_character' | 'normalized_length';
      readonly minimumLength: number; readonly maximumLength: number; readonly lengthUnit: 'utf16';
    } };

const trimCodeUnits = new Set<number>(TRIM_UNITS);
const rawControls = /[\\u0000-\\u001f\\u007f-\\u009f]/u;

/** Reject raw controls before trimming; preserve UTF-16 length and the exact owner trim set. */
export function normalizeLabel(ruleName: LabelRuleName, raw: unknown): LabelValidationResult {
  if (typeof ruleName !== 'string' || !Object.hasOwn(labelValidationMetadata.rules, ruleName)) {
    throw new Error('PKV003 label validation rule is not declared');
  }
  const rule = labelValidationMetadata.rules[ruleName];
  const failure = (code: 'type' | 'control_character' | 'normalized_length'): LabelValidationResult => ({
    valid: false, error: { code, minimumLength: rule.minimumLength, maximumLength: rule.maximumLength, lengthUnit: 'utf16' },
  });
  if (typeof raw !== 'string') return failure('type');
  if (rawControls.test(raw)) return failure('control_character');
  let start = 0;
  let end = raw.length;
  while (start < end && trimCodeUnits.has(raw.charCodeAt(start))) start++;
  while (end > start && trimCodeUnits.has(raw.charCodeAt(end - 1))) end--;
  const value = raw.slice(start, end);
  if (value.length < rule.minimumLength || value.length > rule.maximumLength) return failure('normalized_length');
  return { valid: true, value };
}
'''
    # Insert metadata last: owned identities may themselves contain placeholder text.
    source = source.replace('TRIM_UNITS', json.dumps(TRIM_CODE_UNITS), 1).replace('DIGEST', json.dumps(digest), 1).replace('METADATA', metadata, 1)
    return source.encode('utf-8')


def preserve_output(path: Path, content: bytes, check: bool) -> None:
    if check:
        require(path.is_file() and path.read_bytes() == content, 'stale or missing output: ' + str(path))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)


def run_native(arguments: list[str], repository: Path, timeout: int) -> str:
    result = subprocess.run(arguments, cwd=repository, capture_output=True, text=True, encoding='utf-8', timeout=timeout)
    if result.returncode:
        raise ValueError('PKV002 native owner exporter failed (exit ' + str(result.returncode) + '):\n' + result.stdout + result.stderr)
    return result.stdout


def export_descriptor(project: Path, repository: Path, configuration: str, timeout: int) -> dict:
    require(project.is_file() and project.suffix == '.csproj', 'owner exporter project must exist')
    # Build first: an old binary must never refresh source-backed descriptor evidence.
    run_native(['dotnet', 'build', str(project), '--no-restore', '--configuration', configuration,
        '--nologo', '--verbosity', 'quiet'], repository, timeout)
    output = run_native(['dotnet', 'run', '--project', str(project), '--no-build', '--no-restore',
        '--no-launch-profile', '--configuration', configuration, '--', 'export'], repository, timeout)
    require(len(output.encode('utf-8')) <= MAX_DESCRIPTOR_BYTES, 'export exceeds descriptor byte bound')
    return parse_descriptor(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    export = commands.add_parser('export', help='Build and run a consumer-owned pure-rule exporter; restore explicitly beforehand')
    export.add_argument('--project', type=Path, required=True)
    export.add_argument('--repository', type=Path, default=Path.cwd())
    export.add_argument('--configuration', choices=['Debug', 'Release'], default='Release')
    export.add_argument('--timeout-seconds', type=int, default=120)
    export.add_argument('--output', type=Path, required=True)
    export.add_argument('--check', action='store_true')
    generate = commands.add_parser('generate', help='Generate a browser validator from the exported owner descriptor')
    generate.add_argument('--descriptor', type=Path, required=True)
    generate.add_argument('--output', type=Path, required=True)
    generate.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.command == 'export':
        require(1 <= args.timeout_seconds <= 600, 'export timeout must be 1-600 seconds')
        value = export_descriptor(args.project.resolve(), args.repository.resolve(), args.configuration, args.timeout_seconds)
        preserve_output(args.output, canonical_bytes(value), args.check)
    else:
        preserve_output(args.output, generate_typescript(read_descriptor(args.descriptor)), args.check)
    print(json.dumps({'status': 'passed', 'command': args.command, 'checked': args.check, 'output': str(args.output)}))
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.TimeoutExpired) as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1)
