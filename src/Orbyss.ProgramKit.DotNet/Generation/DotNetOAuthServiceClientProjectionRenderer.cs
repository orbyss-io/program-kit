    internal static ImmutableArray<GeneratedOutput> Render(
        DotNetSecurityConfiguration security)
    {
        if (security.OAuthClientCredentials.IsDefaultOrEmpty &&
            security.OAuthTokenExchanges.IsDefaultOrEmpty)
        {
            return [];
        }

        return
        [
            Output("ProgramKitOAuthGrantKind", RenderGrantKind()),
            Output("ProgramKitOAuthTokenKind", RenderTokenKind()),
            Output("ProgramKitOAuthTokenSourceValue", RenderTokenSourceValue()),
            Output("ProgramKitOAuthAccessToken", RenderAccessToken()),
            Output("IProgramKitOAuthTokenSource", RenderTokenSource()),
            Output("IProgramKitOAuthClientCredentialProvider", RenderCredentialProvider()),
            Output("IProgramKitOAuthClientAssertionProvider", RenderClientAssertionProvider()),
            Output("ProgramKitOAuthProfile", RenderProfile()),
            Output("ProgramKitOAuthTokenResponse", RenderTokenResponse()),
            Output("ProgramKitOAuthProfileCatalog", RenderCatalog(security)),
            Output("ProgramKitOAuthTokenEndpointClient", RenderClient()),
            Output("ProgramKitOAuthBearerHandler", RenderHandler()),
        ];
    }

    internal static string RenderRegistration(DotNetSecurityConfiguration security)
    {
        if (security.OAuthClientCredentials.IsDefaultOrEmpty &&
            security.OAuthTokenExchanges.IsDefaultOrEmpty)
        {
            return string.Empty;
        }

        var builder = new StringBuilder();
        builder.AppendLine("builder.Services.AddMemoryCache();");
        builder.AppendLine("builder.Services.AddSingleton<global::GeneratedHost.Hosting.ProgramKitOAuthTokenEndpointClient>();");
        foreach (var profile in security.OAuthClientCredentials
                     .Select(static item => (item.ClientName, item.RequestTimeoutSeconds))
                     .Concat(security.OAuthTokenExchanges.Select(static item =>
                         (item.ClientName, item.RequestTimeoutSeconds)))
                     .OrderBy(static item => item.ClientName, StringComparer.Ordinal))
        {
            builder.Append("builder.Services.AddHttpClient(")
                .Append(Literal(string.Concat("ProgramKit.OAuth.", profile.ClientName)))
                .Append(", client => client.Timeout = global::System.TimeSpan.FromSeconds(")
                .Append(profile.RequestTimeoutSeconds.ToString(CultureInfo.InvariantCulture))
                .AppendLine("));");
        }

        return builder.ToString();
    }

