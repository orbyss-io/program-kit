    private static bool IsNamedTypeDeclaration(SyntaxNode node) =>
        node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax;

    private static string GetDeclaredTypeName(SyntaxNode declaration) =>
        declaration switch
        {
            BaseTypeDeclarationSyntax type => type.Identifier.ValueText,
            DelegateDeclarationSyntax @delegate =>
                @delegate.Identifier.ValueText,
            _ => throw new InvalidOperationException(
                "The supplied syntax node is not a named type declaration."),
        };

    private static string GetDeclaredNamespace(SyntaxNode declaration)
    {
        var namespaceNames = declaration
            .Ancestors()
            .OfType<BaseNamespaceDeclarationSyntax>()
            .Reverse()
            .Select(static @namespace => @namespace.Name.ToString());
        return string.Join(".", namespaceNames);
    }

