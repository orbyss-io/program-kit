    private static int FindPathSegment(string path, string segment)
    {
        if (path.Equals(segment, StringComparison.Ordinal))
        {
            return 0;
        }

        if (path.StartsWith(
                string.Concat(segment, "/"),
                StringComparison.Ordinal))
        {
            return 0;
        }

        var marker = string.Concat("/", segment, "/");
        var markerIndex = path.IndexOf(marker, StringComparison.Ordinal);
        return markerIndex < 0 ? -1 : markerIndex + 1;
    }

    private static (
        ImmutableDictionary<string, string> Entries,
        ImmutableArray<string> Errors)
        ParseSuppressionLedgers(
            ImmutableArray<AdditionalText> additionalFiles,
            string? canonicalLedgerPath,
            CancellationToken cancellationToken)
    {
        var entries = ImmutableDictionary.CreateBuilder<string, string>(
            StringComparer.Ordinal);
        var errors = ImmutableArray.CreateBuilder<string>();
        var namedLedgerFiles = additionalFiles
            .Where(file => string.Equals(
                Path.GetFileName(file.Path),
                SuppressionLedgerFileName,
                StringComparison.OrdinalIgnoreCase))
            .ToImmutableArray();
        if (canonicalLedgerPath is null)
        {
            errors.Add(
                "compiler-visible canonical suppression-ledger path is missing");
            return (entries.ToImmutable(), errors.ToImmutable());
        }

        string canonicalFullPath;
        try
        {
            canonicalFullPath = Path.GetFullPath(canonicalLedgerPath);
        }
        catch (Exception exception)
        {
            errors.Add(
                "compiler-visible canonical suppression-ledger path is " +
                $"invalid ({exception.GetType().Name})");
            return (entries.ToImmutable(), errors.ToImmutable());
        }

        var ledgerFiles = namedLedgerFiles
            .Where(file => PathsEqual(file.Path, canonicalFullPath))
            .ToImmutableArray();
        if (ledgerFiles.Length != 1)
        {
            errors.Add(
                $"required canonical AdditionalFile '{canonicalFullPath}' must " +
                $"appear exactly once; observed {ledgerFiles.Length}");
        }

        foreach (var extraLedger in namedLedgerFiles
                     .Where(file => !PathsEqual(file.Path, canonicalFullPath)))
        {
            errors.Add(
                $"unapproved alternate suppression ledger '{extraLedger.Path}'");
        }

        foreach (var ledgerFile in ledgerFiles)
        {
            SourceText? sourceText;
            try
            {
                sourceText = ledgerFile.GetText(cancellationToken);
            }
            catch (Exception exception)
            {
                errors.Add(
                    $"{ledgerFile.Path}: could not be read " +
                    $"({exception.GetType().Name})");
                continue;
            }

            if (sourceText is null)
            {
                errors.Add($"{ledgerFile.Path}: could not be read");
                continue;
            }

            for (var index = 0; index < sourceText.Lines.Count; index++)
            {
                var lineNumber = index + 1;
                var line = sourceText.Lines[index].ToString();
                if (string.IsNullOrWhiteSpace(line) ||
                    line.TrimStart().StartsWith('#'))
                {
                    continue;
                }

                ParseSuppressionLedgerLine(
                    ledgerFile.Path,
                    lineNumber,
                    line,
                    entries,
                    errors);
            }
        }

        return (entries.ToImmutable(), errors.ToImmutable());
    }

    private static ImmutableArray<string> ValidateGlobalLedgerInventory(
        ImmutableDictionary<string, string> approvedSuppressions,
        string suppressionLedgerPath)
    {
        var errors = ImmutableArray.CreateBuilder<string>();
        try
        {
            var ledgerDirectory = Path.GetDirectoryName(
                Path.GetFullPath(suppressionLedgerPath));
            var programKitDirectory = ledgerDirectory is null
                ? null
                : Directory.GetParent(ledgerDirectory)?.FullName;
            if (programKitDirectory is null)
            {
                errors.Add(
                    "canonical ledger is not below a Program Kit root");
                return errors.ToImmutable();
            }

            var projectDirectories =
                new Dictionary<string, List<string>>(StringComparer.Ordinal);
            foreach (var projectFile in Directory.EnumerateFiles(
                         programKitDirectory,
                         "*.csproj",
                         SearchOption.AllDirectories))
            {
                var relativeProjectPath = Path.GetRelativePath(
                    programKitDirectory,
                    projectFile);
                if (SplitPath(relativeProjectPath).Any(segment =>
                        segment is "Fixtures" or "bin" or "obj"))
                {
                    continue;
                }

                var projectName =
                    Path.GetFileNameWithoutExtension(projectFile);
                if (!projectDirectories.TryGetValue(
                        projectName,
                        out var directories))
                {
                    directories = [];
                    projectDirectories.Add(projectName, directories);
                }

                directories.Add(
                    Path.GetDirectoryName(projectFile)
                    ?? programKitDirectory);
            }

            foreach (var entry in approvedSuppressions)
            {
                var components = entry.Key.Split(LedgerKeySeparator);
                if (components.Length != 5)
                {
                    continue;
                }

                if (components[3] == "CompilerNoWarn")
                {
                    continue;
                }

                var projectName = components[1];
                var sourcePath = components[2];
                if (!projectDirectories.TryGetValue(
                        projectName,
                        out var directories))
                {
                    errors.Add(
                        $"approved entry references unknown project " +
                        $"'{projectName}': {entry.Value}");
                    continue;
                }

                if (directories.Count != 1)
                {
                    errors.Add(
                        $"approved entry references ambiguous project " +
                        $"'{projectName}': {entry.Value}");
                    continue;
                }

                var projectDirectory = Path.GetFullPath(directories[0]);
                var fullSourcePath = Path.GetFullPath(
                    Path.Combine(
                        projectDirectory,
                        sourcePath.Replace(
                            '/',
                            Path.DirectorySeparatorChar)));
                var projectPrefix = string.Concat(
                    projectDirectory.TrimEnd(
                        Path.DirectorySeparatorChar,
                        Path.AltDirectorySeparatorChar),
                    Path.DirectorySeparatorChar);
                if (!fullSourcePath.StartsWith(
                        projectPrefix,
                        OperatingSystem.IsWindows()
                            ? StringComparison.OrdinalIgnoreCase
                            : StringComparison.Ordinal) ||
                    !File.Exists(fullSourcePath))
                {
                    errors.Add(
                        $"approved entry references missing project source " +
                        $"'{projectName}/{sourcePath}': {entry.Value}");
                }
            }
        }
        catch (Exception exception)
        {
            errors.Add(
                "global warning-suppression inventory could not be " +
                $"validated ({exception.GetType().Name})");
        }

        return errors.ToImmutable();
    }

    private static bool PathsEqual(string left, string right)
    {
        try
        {
            return string.Equals(
                Path.GetFullPath(left),
                Path.GetFullPath(right),
                OperatingSystem.IsWindows()
                    ? StringComparison.OrdinalIgnoreCase
                    : StringComparison.Ordinal);
        }
        catch (Exception)
        {
            return false;
        }
    }

    private static void ParseSuppressionLedgerLine(
        string ledgerPath,
        int lineNumber,
        string line,
        ImmutableDictionary<string, string>.Builder entries,
        ImmutableArray<string>.Builder errors)
    {
        var columns = line.Split('\t');
        if (columns.Length != 8)
        {
            errors.Add(
                $"{ledgerPath}:{lineNumber}: expected 8 tab-separated columns");
            return;
        }

        var diagnosticId = NormalizeDiagnosticId(columns[0]);
        var projectName = columns[1].Trim();
        var sourcePath = NormalizePath(columns[2].Trim());
        var suppressionKind = columns[3].Trim();
        var target = columns[4].Trim();
        var approvalId = columns[5].Trim();
        var approvalDate = columns[6].Trim();
        var rationale = columns[7].Trim();
        var problem = ValidateSuppressionLedgerEntry(
            diagnosticId,
            projectName,
            sourcePath,
            suppressionKind,
            target,
            approvalId,
            approvalDate,
            rationale);
        if (problem is not null)
        {
            errors.Add($"{ledgerPath}:{lineNumber}: {problem}");
            return;
        }

        var key = CreateSuppressionKey(
            diagnosticId,
            projectName,
            sourcePath,
            suppressionKind,
            target);
        var display =
            $"{diagnosticId} in {projectName}/{sourcePath} ({suppressionKind}, " +
            $"{target}, {approvalId}, {approvalDate})";
        if (!entries.TryAdd(key, display))
        {
            errors.Add($"{ledgerPath}:{lineNumber}: duplicate entry {display}");
        }
    }

    private static string? ValidateSuppressionLedgerEntry(
        string diagnosticId,
        string projectName,
        string sourcePath,
        string suppressionKind,
        string target,
        string approvalId,
        string approvalDate,
        string rationale)
    {
        if (string.IsNullOrWhiteSpace(diagnosticId) ||
            !diagnosticId.All(character =>
                char.IsAsciiLetterOrDigit(character)))
        {
            return "diagnostic-id must contain ASCII letters and digits only";
        }

        if (string.IsNullOrWhiteSpace(projectName))
        {
            return "project-name is required";
        }

        if (suppressionKind == "CompilerNoWarn")
        {
            if (sourcePath != "-")
            {
                return "compiler suppression source path must be -";
            }
        }
        else if (string.IsNullOrWhiteSpace(sourcePath) ||
                 Path.IsPathRooted(sourcePath) ||
                 SplitPath(sourcePath).Any(segment =>
                     segment is "." or "..") ||
                 !sourcePath.EndsWith(".cs", StringComparison.Ordinal))
        {
            return "source path must be a normalized project-relative .cs path";
        }

        if (suppressionKind is not
            ("SuppressMessageAttribute" or
             "UnconditionalSuppressMessageAttribute" or
             "PragmaWarningDisable" or
             "CompilerNoWarn"))
        {
            return "suppression-kind is not supported";
        }

        if (string.IsNullOrWhiteSpace(target))
        {
            return "target is required";
        }

        if (suppressionKind == "CompilerNoWarn")
        {
            if (diagnosticId != "CS1701")
            {
                return "compiler suppression diagnostic must be CS1701";
            }

            if (!IsValidCompilerNoWarnTarget(target))
            {
                return "compiler suppression target must bind MSTest.Sdk 4.3.2, " +
                    "the approved locked package closure and assembly set, " +
                    "the .NET 10 runtime identity, absent .NET 10 assets, and " +
                    "mandatory test-toolchain review";
            }
        }
        else if (suppressionKind == "PragmaWarningDisable" &&
            !IsValidPragmaRangeTarget(target))
        {
            return "pragma target must bind an exact lines:<disable>-<restore> range";
        }

        if (suppressionKind is not
                ("PragmaWarningDisable" or "CompilerNoWarn") &&
            !IsValidAttributeTarget(target))
        {
            return "attribute target must bind symbol, attribute-target, " +
                "scope, and message-id";
        }

        if (!approvalId.StartsWith(
                "human-approval:",
                StringComparison.Ordinal) ||
            approvalId.Length <= "human-approval:".Length)
        {
            return "approval-id must identify an explicit human approval";
        }

        if (!DateOnly.TryParseExact(
                approvalDate,
                "yyyy-MM-dd",
                CultureInfo.InvariantCulture,
                DateTimeStyles.None,
                out _))
        {
            return "approval-date must use yyyy-MM-dd";
        }

        if (rationale.Length < 12)
        {
            return "rationale must explain why the warning cannot be resolved";
        }

        return null;
    }

    private static bool IsValidCompilerNoWarnTarget(string target)
    {
        var components = target.Split('|');
        if (components.Length != 6 ||
            components[0] != "mstest-sdk:4.3.2" ||
            components[1] != "closure:cs1701-mstest-sdk-4.3.2-v1" ||
            components[2] != "assembly-set:cs1701-mstest-sdk-4.3.2-v1" ||
            components[3] != "system-runtime:10.0.0.0" ||
            components[4] != "net10-assets:absent" ||
            components[5] != "review-on:test-toolchain-change")
        {
            return false;
        }

        return true;
    }

    private static bool IsValidPragmaRangeTarget(string target)
    {
        const string prefix = "lines:";
        if (!target.StartsWith(prefix, StringComparison.Ordinal))
        {
            return false;
        }

        var range = target[prefix.Length..].Split('-');
        return range.Length == 2 &&
            int.TryParse(
                range[0],
                NumberStyles.None,
                CultureInfo.InvariantCulture,
                out var disableLine) &&
            int.TryParse(
                range[1],
                NumberStyles.None,
                CultureInfo.InvariantCulture,
                out var restoreLine) &&
            disableLine > 0 &&
            restoreLine > disableLine;
    }

    private static bool IsValidAttributeTarget(string target)
    {
        const string attributeTargetMarker = "|attribute-target:";
        const string scopeMarker = "|scope:";
        const string messageIdMarker = "|message-id:";
        var attributeTargetIndex = target.IndexOf(
            attributeTargetMarker,
            StringComparison.Ordinal);
        var scopeIndex = target.IndexOf(
            scopeMarker,
            StringComparison.Ordinal);
        var messageIdIndex = target.IndexOf(
            messageIdMarker,
            StringComparison.Ordinal);
        if (attributeTargetIndex <= 0 ||
            scopeIndex <=
                attributeTargetIndex + attributeTargetMarker.Length ||
            messageIdIndex <= scopeIndex + scopeMarker.Length)
        {
            return false;
        }

        var attributeTarget = target[
            (attributeTargetIndex + attributeTargetMarker.Length)..scopeIndex];
        var scope = target[
            (scopeIndex + scopeMarker.Length)..messageIdIndex];
        var messageId = target[
            (messageIdIndex + messageIdMarker.Length)..];
        string[] supportedScopes =
        [
            "default",
            "member",
            "module",
            "namespace",
            "namespaceanddescendants",
            "resource",
            "type",
        ];
        string[] supportedAttributeTargets =
        [
            "default",
            "assembly",
            "module",
            "type",
            "method",
            "property",
            "field",
            "event",
            "param",
            "return",
        ];
        return supportedAttributeTargets.Contains(
                attributeTarget,
                StringComparer.Ordinal) &&
            supportedScopes.Contains(
                scope,
                StringComparer.OrdinalIgnoreCase) &&
            !string.IsNullOrWhiteSpace(messageId);
    }

    private static string CreateSuppressionKey(
        string diagnosticId,
        string projectName,
        string sourcePath,
        string suppressionKind,
        string target) =>
        string.Join(
            LedgerKeySeparator,
            diagnosticId,
            projectName,
            NormalizePath(sourcePath),
            suppressionKind,
            target);

    private static bool IsSuppressionForProject(
        string suppressionKey,
        string projectName)
    {
        var components = suppressionKey.Split(LedgerKeySeparator);
        return components.Length == 5 &&
            components[3] != "CompilerNoWarn" &&
            string.Equals(
                components[1],
                projectName,
                StringComparison.Ordinal);
    }

    private static string NormalizeDiagnosticId(string value)
    {
        var normalized = value.Trim();
        var titleSeparator = normalized.IndexOf(':');
        normalized = (titleSeparator < 0
                ? normalized
                : normalized[..titleSeparator])
            .Trim()
            .ToUpperInvariant();
        return normalized.All(char.IsAsciiDigit)
            ? string.Concat("CS", normalized.PadLeft(4, '0'))
            : normalized;
    }

