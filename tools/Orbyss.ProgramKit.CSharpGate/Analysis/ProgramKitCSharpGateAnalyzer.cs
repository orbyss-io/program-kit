    private static bool IsAllowedTestIntentPath(
        string projectName,
        string[] folderSegments,
        bool isTypeFree)
    {
        if (!IsTestProject(projectName) ||
            string.Equals(
                projectName,
                "Orbyss.ProgramKit.ConformanceTests",
                StringComparison.Ordinal))
        {
            return true;
        }

        if (!string.Equals(
                projectName,
                "Orbyss.ProgramKit.UnitTests",
                StringComparison.Ordinal))
        {
            if (folderSegments[0] == "TestSupport")
            {
                return true;
            }

            var testedProjectName = GetTestedProjectName(projectName);
            return testedProjectName is not null &&
                IsAllowedIntentRoot(
                    testedProjectName,
                    folderSegments[0]);
        }

        var domain = folderSegments[0];
        if (domain == "TestSupport")
        {
            return true;
        }

        if (domain == "Serialization")
        {
            if (folderSegments.Length < 2 ||
                !string.Equals(
                    folderSegments[1],
                    "Json",
                    StringComparison.Ordinal))
            {
                return false;
            }

            if (folderSegments.Length == 2)
            {
                return isTypeFree;
            }

            return folderSegments[2] == "TestSupport" ||
                IsAllowedIntentRoot(
                    "Orbyss.ProgramKit.Serialization.JSON",
                    folderSegments[2]);
        }

        if (folderSegments.Length == 1)
        {
            return isTypeFree;
        }

        var productProject = domain switch
        {
            "Architecture" => "Orbyss.ProgramKit.Architecture",
            "Artifacts" => "Orbyss.ProgramKit.Artifacts",
            "Development" => "Orbyss.ProgramKit.Development",
            "Modularity" => "Orbyss.ProgramKit.Modularity",
            "Planning" => "Orbyss.ProgramKit.Planning",
            "Quality" => "Orbyss.ProgramKit.Quality",
            "Tasks" => "Orbyss.ProgramKit.Tasks.Core",
            "Workbench" => "Orbyss.ProgramKit.Workbench",
            _ => null,
        };
        return productProject is not null &&
            IsAllowedIntentRoot(productProject, folderSegments[1]);
    }

    private static string? GetTestedProjectName(string testProjectName)
    {
        string[] suffixes =
        [
            ".ConformanceTests",
            ".IntegrationTests",
            ".UnitTests",
            ".Tests",
        ];
        var suffix = suffixes.FirstOrDefault(candidate =>
            testProjectName.EndsWith(
                candidate,
                StringComparison.Ordinal));
        return suffix is null
            ? null
            : testProjectName[..^suffix.Length];
    }

