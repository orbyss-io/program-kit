    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(
            GeneratedCodeAnalysisFlags.Analyze |
            GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(StartCompilationAnalysis);
    }

    private static void StartCompilationAnalysis(
        CompilationStartAnalysisContext context)
    {
        var globalOptions =
            context.Options.AnalyzerConfigOptionsProvider.GlobalOptions;
        var hasProjectDirectory = TryGetGlobalOption(
            globalOptions,
            "build_property.MSBuildProjectDirectory",
            out var projectDirectory);
        var hasProjectName = TryGetGlobalOption(
            globalOptions,
            "build_property.MSBuildProjectName",
            out var projectName);
        var hasRootNamespace = TryGetGlobalOption(
            globalOptions,
            "build_property.RootNamespace",
            out var rootNamespace);
        var hasSuppressionLedgerPath = TryGetGlobalOption(
            globalOptions,
            "build_property.ProgramKitWarningApprovalLedgerPath",
            out var suppressionLedgerPath);
        var hasCompilerInvocationNonce = TryGetGlobalOption(
            globalOptions,
            "build_property.ProgramKitCompilerInvocationNonce",
            out var compilerInvocationNonce);

        var (allApprovedSuppressions, ledgerErrors) = ParseSuppressionLedgers(
            context.Options.AdditionalFiles,
            hasSuppressionLedgerPath ? suppressionLedgerPath : null,
            context.CancellationToken);
        var approvedSuppressions = hasProjectName
            ? allApprovedSuppressions
                .Where(entry => IsSuppressionForProject(
                    entry.Key,
                    projectName))
                .ToImmutableDictionary(
                    StringComparer.Ordinal)
            : ImmutableDictionary<string, string>.Empty.WithComparers(
                StringComparer.Ordinal);
        var usedSuppressions =
            new ConcurrentDictionary<string, byte>(StringComparer.Ordinal);

        context.RegisterSyntaxTreeAction(treeContext =>
            AnalyzeSyntaxTree(
                treeContext,
                context.Compilation,
                hasProjectDirectory ? projectDirectory : null,
                hasProjectName ? projectName : null,
                hasRootNamespace ? rootNamespace : null,
                hasCompilerInvocationNonce ? compilerInvocationNonce : null,
                approvedSuppressions,
                usedSuppressions));

        context.RegisterCompilationEndAction(endContext =>
        {
            if (!hasProjectDirectory)
            {
                ReportMissingConfiguration(
                    endContext,
                    "MSBuildProjectDirectory");
            }

            if (!hasProjectName)
            {
                ReportMissingConfiguration(endContext, "MSBuildProjectName");
            }

            if (!hasRootNamespace)
            {
                ReportMissingConfiguration(endContext, "RootNamespace");
            }

            if (!hasSuppressionLedgerPath)
            {
                ReportMissingConfiguration(
                    endContext,
                    "ProgramKitWarningApprovalLedgerPath");
            }

            if (!hasCompilerInvocationNonce)
            {
                ReportMissingConfiguration(
                    endContext,
                    "ProgramKitCompilerInvocationNonce");
            }

            foreach (var error in ledgerErrors)
            {
                endContext.ReportDiagnostic(
                    Diagnostic.Create(
                        InvalidSuppressionLedger,
                        Location.None,
                        error));
            }

            if (hasProjectName &&
                string.Equals(
                    projectName,
                    "Orbyss.ProgramKit.CSharpGate",
                    StringComparison.Ordinal) &&
                hasSuppressionLedgerPath)
            {
                foreach (var error in ValidateGlobalLedgerInventory(
                             allApprovedSuppressions,
                             suppressionLedgerPath))
                {
                    endContext.ReportDiagnostic(
                        Diagnostic.Create(
                            InvalidSuppressionLedger,
                            Location.None,
                            error));
                }
            }

            foreach (var entry in approvedSuppressions)
            {
                if (!usedSuppressions.ContainsKey(entry.Key))
                {
                    endContext.ReportDiagnostic(
                        Diagnostic.Create(
                            InvalidSuppressionLedger,
                            Location.None,
                            $"approved entry is stale or did not match a " +
                            $"compiled suppression: {entry.Value}"));
                }
            }
        });
    }

    private static void AnalyzeSyntaxTree(
        SyntaxTreeAnalysisContext context,
        Compilation compilation,
        string? projectDirectory,
        string? projectName,
        string? rootNamespace,
        string? compilerInvocationNonce,
        ImmutableDictionary<string, string> approvedSuppressions,
        ConcurrentDictionary<string, byte> usedSuppressions)
    {
        var cancellationToken = context.CancellationToken;
        var root = context.Tree.GetRoot(cancellationToken);
        var semanticModel = compilation.GetSemanticModel(context.Tree);
        var typeDeclarations = root
            .DescendantNodes()
            .Where(IsNamedTypeDeclaration)
            .ToImmutableArray();
        var sourceText = context.Tree.GetText(cancellationToken);
        var claimsProgramKitGeneratedOwnership =
            HasExactGeneratedSourceOwnershipHeader(sourceText);
        var claimsGeneratedCode = HasGeneratedCodeClaim(
            sourceText,
            root,
            semanticModel,
            cancellationToken);

        var hasSourceIdentity = TryResolveSourceIdentity(
            context,
            projectDirectory,
            claimsProgramKitGeneratedOwnership,
            claimsGeneratedCode,
            out var relativeSourcePath,
            out var ledgerSourcePath,
            out var isAmbientGenerated);

        if (isAmbientGenerated)
        {
            return;
        }

        AnalyzeTypeCount(context, context.Tree.FilePath, typeDeclarations);

        if (hasSourceIdentity &&
            projectName is not null &&
            rootNamespace is not null)
        {
            AnalyzeSourceStructure(
                context,
                root,
                relativeSourcePath,
                projectName,
                rootNamespace,
                typeDeclarations,
                claimsProgramKitGeneratedOwnership,
                compilerInvocationNonce);
        }

        AnalyzeCreatedInstanceInvocations(context, semanticModel, root);
        AnalyzeWarningSuppressions(
            context,
            semanticModel,
            root,
            projectName,
            ledgerSourcePath,
            approvedSuppressions,
            usedSuppressions);
        AnalyzeNullableDirectives(context, root);
        AnalyzeInternalHelpers(context, semanticModel, root);
        AnalyzeBehavioralServices(context, semanticModel, root);
        AnalyzeBehavioralInterfaceReturns(context, semanticModel, root);

        if (projectName is not null && hasSourceIdentity)
        {
            if (!IsTestProject(projectName) &&
                !IsCompositionPath(relativeSourcePath))
            {
                AnalyzeServiceConstruction(context, semanticModel, root);
            }

            AnalyzeConcreteConstructorDependencies(
                context,
                compilation,
                semanticModel,
                root,
                context.CancellationToken);
        }
    }

    private static void AnalyzeTypeCount(
        SyntaxTreeAnalysisContext context,
        string sourcePath,
        ImmutableArray<SyntaxNode> declarations)
    {
        if (declarations.Length <= 1)
        {
            return;
        }

        context.ReportDiagnostic(
            Diagnostic.Create(
                OneNamedTypePerFile,
                declarations[1].GetLocation(),
                GetDisplayFileName(sourcePath),
                declarations.Length));
    }

    private static void AnalyzeSourceStructure(
        SyntaxTreeAnalysisContext context,
        SyntaxNode root,
        string relativeSourcePath,
        string projectName,
        string rootNamespace,
        ImmutableArray<SyntaxNode> declarations,
        bool claimsProgramKitGeneratedOwnership,
        string? compilerInvocationNonce)
    {
        var sourceFileName = Path.GetFileName(relativeSourcePath);
        var relativeDirectory = Path.GetDirectoryName(relativeSourcePath);
        var location = declarations.Length > 0
            ? declarations[0].GetLocation()
            : root.GetLocation();

        if (IsCompilerInvocationReceiptPath(
                relativeSourcePath,
                compilerInvocationNonce))
        {
            if (!IsExactCompilerInvocationReceipt(
                    context.Tree.GetText(context.CancellationToken),
                    root,
                    declarations,
                    claimsProgramKitGeneratedOwnership,
                    compilerInvocationNonce!))
            {
                ReportGeneratedConvention(
                    context,
                    context.Tree.FilePath);
            }

            return;
        }

        if (string.IsNullOrWhiteSpace(relativeDirectory) ||
            string.Equals(relativeDirectory, ".", StringComparison.Ordinal))
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    IntentFolderRequired,
                    location,
                    sourceFileName,
                    "project root"));
            return;
        }

        var folderSegments = SplitPath(relativeDirectory);
        if (folderSegments.Length == 0 ||
            !IsAllowedIntentRoot(projectName, folderSegments[0]))
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    IntentFolderRequired,
                    location,
                    sourceFileName,
                    folderSegments.Length == 0
                        ? "missing intent"
                        : folderSegments[0]));
            return;
        }

        if (!IsAllowedTestIntentPath(
                projectName,
                folderSegments,
                declarations.Length == 0))
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    IntentFolderRequired,
                    location,
                    sourceFileName,
                    string.Join("/", folderSegments)));
            return;
        }

        var containsTopLevelLogic =
            ContainsTopLevelLogic(root);
        if (containsTopLevelLogic)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    TypeFreeSourceContainsLogic,
                    location,
                    sourceFileName));
        }

        if (declarations.Length == 0)
        {
            if (!containsTopLevelLogic &&
                !IsApprovedTypeFreeSource(root))
            {
                context.ReportDiagnostic(
                    Diagnostic.Create(
                        TypeFreeSourceContainsLogic,
                        location,
                        sourceFileName));
            }

            return;
        }

        if (declarations.Length != 1)
        {
            return;
        }

        AnalyzeFileName(
            context,
            relativeSourcePath,
            declarations[0]);
        AnalyzeNamespace(
            context,
            relativeDirectory,
            rootNamespace,
            declarations[0]);
    }

    private static bool IsApprovedTypeFreeSource(SyntaxNode root) =>
        root is CompilationUnitSyntax compilationUnit &&
        compilationUnit.Members.Count == 0;

    private static bool IsExactCompilerInvocationReceipt(
        SourceText sourceText,
        SyntaxNode root,
        ImmutableArray<SyntaxNode> declarations,
        bool claimsProgramKitGeneratedOwnership,
        string compilerInvocationNonce)
    {
        if (!claimsProgramKitGeneratedOwnership ||
            declarations.Length != 0 ||
            !IsApprovedTypeFreeSource(root) ||
            sourceText.Lines.Count < 2 ||
            !string.Equals(
                sourceText.ToString(sourceText.Lines[0].Span),
                GeneratedSourceOwnershipHeader,
                StringComparison.Ordinal) ||
            !string.Equals(
                sourceText.ToString(sourceText.Lines[1].Span),
                string.Concat(
                    CompilerInvocationReceiptMarkerPrefix,
                    compilerInvocationNonce),
                StringComparison.Ordinal))
        {
            return false;
        }

        return sourceText.Lines
            .Skip(2)
            .All(line => string.IsNullOrWhiteSpace(
                sourceText.ToString(line.Span)));
    }

    private static bool IsCompilerInvocationReceiptPath(
        string relativeSourcePath,
        string? compilerInvocationNonce) =>
        !string.IsNullOrWhiteSpace(compilerInvocationNonce) &&
        string.Equals(
            NormalizePath(relativeSourcePath),
            string.Concat(
                CompilerInvocationReceiptPathPrefix,
                compilerInvocationNonce,
                ".cs"),
            StringComparison.Ordinal);

    private static bool ContainsTopLevelLogic(SyntaxNode root) =>
        root is CompilationUnitSyntax compilationUnit &&
        compilationUnit.Members.Any(static member =>
            member is GlobalStatementSyntax);

    private static void AnalyzeFileName(
        SyntaxTreeAnalysisContext context,
        string sourcePath,
        SyntaxNode declaration)
    {
        var declaredName = GetDeclaredTypeName(declaration);
        var fileName = Path.GetFileNameWithoutExtension(sourcePath);
        if (string.Equals(fileName, declaredName, StringComparison.Ordinal))
        {
            return;
        }

        context.ReportDiagnostic(
            Diagnostic.Create(
                FileNameMatchesType,
                declaration.GetLocation(),
                Path.GetFileName(sourcePath),
                declaredName));
    }

    private static void AnalyzeNamespace(
        SyntaxTreeAnalysisContext context,
        string relativeDirectory,
        string rootNamespace,
        SyntaxNode declaration)
    {
        var folderNamespace = string.Join(".", SplitPath(relativeDirectory));
        var expectedNamespace = string.Concat(
            rootNamespace,
            ".",
            folderNamespace);
        var observedNamespace = GetDeclaredNamespace(declaration);
        if (string.Equals(
                expectedNamespace,
                observedNamespace,
                StringComparison.Ordinal))
        {
            return;
        }

        context.ReportDiagnostic(
            Diagnostic.Create(
                NamespaceMatchesFolders,
                declaration.GetLocation(),
                GetDeclaredTypeName(declaration),
                expectedNamespace,
                observedNamespace));
    }

    private static void AnalyzeCreatedInstanceInvocations(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        foreach (var invocationSyntax in root
                     .DescendantNodes()
                     .OfType<InvocationExpressionSyntax>())
        {
            var receiver = GetInvocationReceiverOperation(
                invocationSyntax,
                semanticModel,
                context.CancellationToken);
            var creation = FindCreatedResultOperation(receiver);
            if (creation is null)
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    CreatedInstanceInvocation,
                    invocationSyntax.GetLocation(),
                    creation.Type?.ToDisplayString() ?? "created instance"));
        }
    }

    private static IOperation? GetInvocationReceiverOperation(
        InvocationExpressionSyntax invocation,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        var invocationOperation = semanticModel.GetOperation(
            invocation,
            cancellationToken);
        if (invocationOperation is IInvocationOperation
            {
                Instance: { } instance,
            })
        {
            return instance;
        }

        if (invocationOperation is IDynamicInvocationOperation
            {
                Operation: { } dynamicOperation,
            })
        {
            return dynamicOperation;
        }

        ExpressionSyntax? receiver = invocation.Expression switch
        {
            MemberAccessExpressionSyntax memberAccess => memberAccess.Expression,
            MemberBindingExpressionSyntax => invocation
                .Ancestors()
                .OfType<ConditionalAccessExpressionSyntax>()
                .FirstOrDefault(candidate =>
                    candidate.WhenNotNull.Span.Contains(invocation.Span))
                ?.Expression,
            _ => invocation.Expression,
        };

        return receiver is null
            ? null
            : semanticModel.GetOperation(receiver, cancellationToken);
    }

    private static IOperation? FindCreatedResultOperation(IOperation? operation)
    {
        while (operation is not null)
        {
            switch (operation)
            {
                case IObjectCreationOperation:
                case ITypeParameterObjectCreationOperation:
                case IArrayCreationOperation:
                case IAnonymousObjectCreationOperation:
                    return operation;
                case IConversionOperation conversion:
                    operation = conversion.Operand;
                    continue;
                case IParenthesizedOperation parenthesized:
                    operation = parenthesized.Operand;
                    continue;
                case IPropertyReferenceOperation propertyReference:
                    operation = propertyReference.Instance;
                    continue;
                case IFieldReferenceOperation
                {
                    Instance: ITupleOperation tuple,
                } tupleField:
                    return FindCreatedTupleElement(tupleField, tuple);
                case IFieldReferenceOperation fieldReference:
                    operation = fieldReference.Instance;
                    continue;
                case IArrayElementReferenceOperation arrayElement:
                    return FindCreatedArrayElement(arrayElement);
                case IDynamicMemberReferenceOperation dynamicMemberReference:
                    operation = dynamicMemberReference.Instance;
                    continue;
                case IConditionalAccessOperation conditionalAccess:
                    operation = conditionalAccess.Operation;
                    continue;
                case IConditionalAccessInstanceOperation conditionalInstance:
                    operation = FindConditionalAccessReceiver(
                        conditionalInstance);
                    continue;
                case IConditionalOperation conditional:
                    return FindCreatedResultOperation(conditional.WhenTrue) ??
                        FindCreatedResultOperation(conditional.WhenFalse);
                case ICoalesceOperation coalesce:
                    return FindCreatedResultOperation(coalesce.Value) ??
                        FindCreatedResultOperation(coalesce.WhenNull);
                case IWithOperation withOperation:
                    operation = withOperation.Operand;
                    continue;
                case IDelegateCreationOperation delegateCreation:
                    operation = delegateCreation.Target;
                    continue;
                case IMethodReferenceOperation methodReference:
                    operation = methodReference.Instance;
                    continue;
                case IUnaryOperation unary:
                    operation = unary.Operand;
                    continue;
                case IAwaitOperation awaitOperation:
                    operation = awaitOperation.Operation;
                    continue;
                case ISwitchExpressionOperation switchExpression:
                    return switchExpression.Arms
                            .Select(arm =>
                                FindCreatedResultOperation(arm.Value))
                            .FirstOrDefault(static created => created is not null) ??
                        FindCreatedResultOperation(switchExpression.Value);
                default:
                    return null;
            }
        }

        return null;
    }

    private static IOperation? FindConditionalAccessReceiver(
        IConditionalAccessInstanceOperation instance)
    {
        for (var parent = instance.Parent;
             parent is not null;
             parent = parent.Parent)
        {
            if (parent is IConditionalAccessOperation conditionalAccess)
            {
                return conditionalAccess.Operation;
            }
        }

        return null;
    }

    private static IOperation? FindCreatedTupleElement(
        IFieldReferenceOperation fieldReference,
        ITupleOperation tuple)
    {
        var tupleFields = fieldReference.Field.ContainingType.TupleElements;
        for (var index = 0;
             index < tupleFields.Length && index < tuple.Elements.Length;
             index++)
        {
            var candidateField =
                tupleFields[index].CorrespondingTupleField ??
                tupleFields[index];
            var referencedField =
                fieldReference.Field.CorrespondingTupleField ??
                fieldReference.Field;
            if (!SymbolEqualityComparer.Default.Equals(
                    candidateField,
                    referencedField))
            {
                continue;
            }

            return FindCreatedResultOperation(tuple.Elements[index]);
        }

        return null;
    }

    private static IOperation? FindCreatedArrayElement(
        IArrayElementReferenceOperation elementReference)
    {
        var arrayReference = UnwrapTransparentOperation(
            elementReference.ArrayReference);
        if (arrayReference is not IArrayCreationOperation
            {
                Initializer: { } initializer,
            })
        {
            return null;
        }

        if (elementReference.Indices.Length == 1 &&
            elementReference.Indices[0].ConstantValue is
            {
                HasValue: true,
                Value: int index,
            } &&
            index >= 0 &&
            index < initializer.ElementValues.Length)
        {
            return FindCreatedResultOperation(
                initializer.ElementValues[index]);
        }

        return initializer.ElementValues
            .Select(FindCreatedResultOperation)
            .FirstOrDefault(static created => created is not null);
    }

    private static IOperation? UnwrapTransparentOperation(
        IOperation operation)
    {
        while (true)
        {
            switch (operation)
            {
                case IConversionOperation conversion:
                    operation = conversion.Operand;
                    continue;
                case IParenthesizedOperation parenthesized:
                    operation = parenthesized.Operand;
                    continue;
                default:
                    return operation;
            }
        }
    }

    private static void AnalyzeWarningSuppressions(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root,
        string? projectName,
        string ledgerSourcePath,
        ImmutableDictionary<string, string> approvedSuppressions,
        ConcurrentDictionary<string, byte> usedSuppressions)
    {
        var warningPragmas = root
            .DescendantTrivia(descendIntoTrivia: true)
            .Select(static trivia => trivia.GetStructure())
            .OfType<PragmaWarningDirectiveTriviaSyntax>()
            .Where(static directive => directive.IsActive)
            .ToImmutableArray();
        foreach (var pragma in warningPragmas)
        {
            if (!pragma.DisableOrRestoreKeyword.IsKind(
                    SyntaxKind.DisableKeyword))
            {
                continue;
            }

            var line = pragma.GetLocation()
                .GetLineSpan()
                .StartLinePosition
                .Line + 1;
            if (pragma.ErrorCodes.Count == 0)
            {
                ReportUnapprovedSuppression(
                    context,
                    pragma.GetLocation(),
                    pragma.ToString());
                continue;
            }

            foreach (var errorCode in pragma.ErrorCodes)
            {
                var diagnosticId = NormalizeDiagnosticId(errorCode.ToString());
                var restoreLine = FindMatchingRestoreLine(
                    warningPragmas,
                    pragma,
                    diagnosticId);
                var target = restoreLine is null
                    ? null
                    : string.Concat(
                        "lines:",
                        line.ToString(CultureInfo.InvariantCulture),
                        "-",
                        restoreLine.Value.ToString(
                            CultureInfo.InvariantCulture));
                if (target is null ||
                    !TryApproveSuppression(
                        projectName,
                        ledgerSourcePath,
                        "PragmaWarningDisable",
                        diagnosticId,
                        target,
                        approvedSuppressions,
                        usedSuppressions))
                {
                    ReportUnapprovedSuppression(
                        context,
                        pragma.GetLocation(),
                        pragma.ToString());
                }
            }
        }

        foreach (var attribute in root.DescendantNodes().OfType<AttributeSyntax>())
        {
            var attributeType = GetAttributeType(
                semanticModel,
                attribute,
                context.CancellationToken);
            var suppressionKind = attributeType?.ToDisplayString() switch
            {
                "System.Diagnostics.CodeAnalysis.SuppressMessageAttribute" =>
                    "SuppressMessageAttribute",
                "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute" =>
                    "UnconditionalSuppressMessageAttribute",
                _ => null,
            };
            if (suppressionKind is null)
            {
                continue;
            }

            var diagnosticId = GetSuppressedDiagnosticId(
                semanticModel,
                attribute,
                context.CancellationToken);
            var target = GetSuppressionTarget(
                semanticModel,
                attribute,
                context.CancellationToken);
            if (diagnosticId is null ||
                target is null ||
                !TryApproveSuppression(
                    projectName,
                    ledgerSourcePath,
                    suppressionKind,
                    diagnosticId,
                    target,
                    approvedSuppressions,
                    usedSuppressions))
            {
                ReportUnapprovedSuppression(
                    context,
                    attribute.GetLocation(),
                    attribute.Name.ToString());
            }
        }
    }

    private static int? FindMatchingRestoreLine(
        ImmutableArray<PragmaWarningDirectiveTriviaSyntax> warningPragmas,
        PragmaWarningDirectiveTriviaSyntax disablePragma,
        string diagnosticId)
    {
        foreach (var candidate in warningPragmas)
        {
            if (candidate.SpanStart <= disablePragma.SpanStart ||
                !candidate.DisableOrRestoreKeyword.IsKind(
                    SyntaxKind.RestoreKeyword) ||
                (candidate.ErrorCodes.Count > 0 &&
                 !candidate.ErrorCodes.Any(errorCode =>
                     string.Equals(
                         NormalizeDiagnosticId(errorCode.ToString()),
                         diagnosticId,
                         StringComparison.Ordinal))))
            {
                continue;
            }

            return candidate.GetLocation()
                .GetLineSpan()
                .StartLinePosition
                .Line + 1;
        }

        return null;
    }

    private static INamedTypeSymbol? GetAttributeType(
        SemanticModel semanticModel,
        AttributeSyntax attribute,
        CancellationToken cancellationToken) =>
        semanticModel.GetSymbolInfo(attribute, cancellationToken).Symbol is
            IMethodSymbol constructor
            ? constructor.ContainingType
            : null;

    private static string? GetSuppressedDiagnosticId(
        SemanticModel semanticModel,
        AttributeSyntax attribute,
        CancellationToken cancellationToken)
    {
        if (semanticModel.GetOperation(
                attribute,
                cancellationToken) is not IAttributeOperation
                {
                    Operation: IObjectCreationOperation creation,
                })
        {
            return null;
        }

        var checkId = creation.Arguments.FirstOrDefault(argument =>
            string.Equals(
                argument.Parameter?.Name,
                "checkId",
                StringComparison.Ordinal));
        return checkId?.Value.ConstantValue is
        {
            HasValue: true,
            Value: string diagnostic,
        }
            ? NormalizeDiagnosticId(diagnostic)
            : null;
    }

    private static string? GetSuppressionTarget(
        SemanticModel semanticModel,
        AttributeSyntax attribute,
        CancellationToken cancellationToken)
    {
        if (attribute.Parent is not AttributeListSyntax attributeList)
        {
            return null;
        }

        var explicitlyTargetedSymbol = GetNamedStringArgument(
            semanticModel,
            attribute,
            "Target",
            cancellationToken);
        string? target;
        if (!string.IsNullOrWhiteSpace(explicitlyTargetedSymbol))
        {
            target = explicitlyTargetedSymbol;
        }
        else if (attributeList.Target?.Identifier.IsKind(
                SyntaxKind.AssemblyKeyword) == true)
        {
            target = "assembly";
        }
        else if (attributeList.Target?.Identifier.IsKind(
                SyntaxKind.ModuleKeyword) == true)
        {
            target = "module";
        }
        else
        {
            var declaration = attributeList.Parent;
            var symbol = declaration is null
                ? null
                : semanticModel.GetDeclaredSymbol(
                    declaration,
                    cancellationToken);
            target = symbol?.GetDocumentationCommentId();
        }

        if (string.IsNullOrWhiteSpace(target))
        {
            return null;
        }

        var attributeTarget = attributeList.Target?.Identifier.ValueText;
        var scope = GetNamedStringArgument(
            semanticModel,
            attribute,
            "Scope",
            cancellationToken);
        var messageId = GetNamedStringArgument(
            semanticModel,
            attribute,
            "MessageId",
            cancellationToken);
        return string.Concat(
            target,
            "|attribute-target:",
            string.IsNullOrWhiteSpace(attributeTarget)
                ? "default"
                : attributeTarget,
            "|scope:",
            string.IsNullOrWhiteSpace(scope) ? "default" : scope.Trim(),
            "|message-id:",
            string.IsNullOrWhiteSpace(messageId)
                ? "-"
                : messageId.Trim());
    }

    private static string? GetNamedStringArgument(
        SemanticModel semanticModel,
        AttributeSyntax attribute,
        string name,
        CancellationToken cancellationToken)
    {
        var argument = attribute.ArgumentList?.Arguments.FirstOrDefault(
            candidate => string.Equals(
                candidate.NameEquals?.Name.Identifier.ValueText,
                name,
                StringComparison.Ordinal));
        if (argument is null)
        {
            return null;
        }

        var constant = semanticModel.GetConstantValue(
            argument.Expression,
            cancellationToken);
        return constant.HasValue && constant.Value is string value
            ? value
            : null;
    }

    private static bool TryApproveSuppression(
        string? projectName,
        string sourcePath,
        string suppressionKind,
        string diagnosticId,
        string target,
        ImmutableDictionary<string, string> approvedSuppressions,
        ConcurrentDictionary<string, byte> usedSuppressions)
    {
        if (projectName is null || string.IsNullOrWhiteSpace(sourcePath))
        {
            return false;
        }

        var key = CreateSuppressionKey(
            diagnosticId,
            projectName,
            sourcePath,
            suppressionKind,
            target);
        if (!approvedSuppressions.ContainsKey(key))
        {
            return false;
        }

        usedSuppressions.TryAdd(key, 0);
        return true;
    }

    private static void ReportUnapprovedSuppression(
        SyntaxTreeAnalysisContext context,
        Location location,
        string suppression)
    {
        context.ReportDiagnostic(
            Diagnostic.Create(
                WarningSuppression,
                location,
                suppression));
    }

    private static void AnalyzeNullableDirectives(
        SyntaxTreeAnalysisContext context,
        SyntaxNode root)
    {
        foreach (var directive in root
                     .DescendantTrivia(descendIntoTrivia: true)
                     .Select(static trivia => trivia.GetStructure())
                     .OfType<NullableDirectiveTriviaSyntax>())
        {
            if (!directive.IsActive ||
                !directive.SettingToken.IsKind(SyntaxKind.DisableKeyword))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    NullableDisable,
                    directive.GetLocation()));
        }
    }

    private static void AnalyzeInternalHelpers(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        foreach (var declaration in root
                     .DescendantNodes()
                     .OfType<TypeDeclarationSyntax>())
        {
            if (semanticModel.GetDeclaredSymbol(
                    declaration,
                    context.CancellationToken) is not INamedTypeSymbol symbol ||
                symbol.TypeKind != TypeKind.Class ||
                (symbol.DeclaredAccessibility != Accessibility.Internal &&
                 !declaration.Modifiers.Any(
                     SyntaxKind.FileKeyword)) ||
                symbol.IsStatic ||
                HasSubstitutableInterfaceContract(symbol) ||
                !InternalHelperSuffixes.Any(suffix =>
                    symbol.Name.EndsWith(suffix, StringComparison.Ordinal)))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    InternalHelperMustBeStatic,
                    declaration.Identifier.GetLocation(),
                    symbol.Name));
        }
    }

    private static void AnalyzeServiceConstruction(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        foreach (var creationSyntax in root
                     .DescendantNodes()
                     .OfType<BaseObjectCreationExpressionSyntax>())
        {
            if (semanticModel.GetOperation(
                    creationSyntax,
                    context.CancellationToken) is not
                    IObjectCreationOperation creation ||
                creation.Type is not INamedTypeSymbol createdType ||
                !IsBehavioralServiceType(createdType))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    ServiceConstructionBoundary,
                    creationSyntax.GetLocation(),
                    createdType.ToDisplayString()));
        }
    }

    private static void AnalyzeConcreteConstructorDependencies(
        SyntaxTreeAnalysisContext context,
        Compilation compilation,
        SemanticModel semanticModel,
        SyntaxNode root,
        CancellationToken cancellationToken)
    {
        foreach (var parameterSyntax in root
                     .DescendantNodes()
                     .OfType<ParameterSyntax>())
        {
            if (!IsConstructorParameter(parameterSyntax) ||
                semanticModel.GetDeclaredSymbol(
                    parameterSyntax,
                    context.CancellationToken) is not IParameterSymbol parameter)
            {
                continue;
            }

            var concreteDependency =
                FindConcreteBehavioralDependency(parameter.Type);
            var behavioralInterfaceDependency =
                FindBehavioralInterfaceDependency(parameter.Type);
            var unsafeRecordDependency =
                IsPositionalRecordParameter(parameterSyntax)
                    ? behavioralInterfaceDependency
                    : null;
            var unsafePrimaryConstructorDependency =
                behavioralInterfaceDependency is not null &&
                HasUnsafePrimaryConstructorParameterUsage(
                    parameter,
                    parameterSyntax,
                    semanticModel,
                    root)
                    ? behavioralInterfaceDependency
                    : null;
            if (concreteDependency is null &&
                unsafeRecordDependency is null &&
                unsafePrimaryConstructorDependency is null)
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    ConcreteConstructorDependency,
                    parameterSyntax.GetLocation(),
                    (concreteDependency ??
                     unsafeRecordDependency ??
                     unsafePrimaryConstructorDependency)!
                        .ToDisplayString()));
        }

        foreach (var variableSyntax in root
                     .DescendantNodes()
                     .OfType<VariableDeclaratorSyntax>())
        {
            if (semanticModel.GetDeclaredSymbol(
                    variableSyntax,
                    context.CancellationToken) is not IFieldSymbol field)
            {
                continue;
            }

            var concreteDependency =
                FindConcreteBehavioralDependency(field.Type);
            var mutableInterfaceDependency =
                FindBehavioralInterfaceDependency(field.Type);
            if (concreteDependency is null &&
                (mutableInterfaceDependency is null ||
                 IsConstructorInjectedInterfaceField(
                     field,
                     variableSyntax,
                     compilation,
                     semanticModel,
                     context.CancellationToken)))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    ConcreteConstructorDependency,
                    variableSyntax.GetLocation(),
                    (concreteDependency ?? mutableInterfaceDependency)!
                        .ToDisplayString()));
        }

        foreach (var propertySyntax in root
                     .DescendantNodes()
                     .OfType<PropertyDeclarationSyntax>())
        {
            if (semanticModel.GetDeclaredSymbol(
                    propertySyntax,
                    context.CancellationToken) is not IPropertySymbol property)
            {
                continue;
            }

            var concreteDependency =
                FindConcreteBehavioralDependency(property.Type);
            var mutableInterfaceDependency =
                FindBehavioralInterfaceDependency(property.Type);
            if (concreteDependency is null &&
                (mutableInterfaceDependency is null ||
                 IsConstructorInjectedInterfaceProperty(
                     property,
                     propertySyntax,
                     compilation,
                     semanticModel,
                     cancellationToken)))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    ConcreteConstructorDependency,
                    propertySyntax.Type.GetLocation(),
                    (concreteDependency ?? mutableInterfaceDependency)!
                        .ToDisplayString()));
        }
    }

    private static bool IsConstructorInjectedInterfaceField(
        IFieldSymbol field,
        VariableDeclaratorSyntax declaration,
        Compilation compilation,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        if (declaration.Initializer is { Value: { } initializer })
        {
            return !field.IsStatic &&
                field.IsReadOnly &&
                IsPrimaryConstructorParameterSource(
                    initializer,
                    semanticModel) &&
                HasConstructorParameterAssignment(
                    field,
                    initializer,
                    compilation,
                    cancellationToken);
        }

        if (field.IsStatic || !field.IsReadOnly)
        {
            return false;
        }

        return HasConstructorParameterAssignment(
            field,
            primaryInitializer: null,
            compilation,
            cancellationToken);
    }

    private static bool IsConstructorInjectedInterfaceProperty(
        IPropertySymbol property,
        PropertyDeclarationSyntax declaration,
        Compilation compilation,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        if (property.ContainingType.TypeKind == TypeKind.Interface ||
            property.IsAbstract)
        {
            return true;
        }

        if (declaration.ExpressionBody is { Expression: { } expression })
        {
            return expression.IsKind(SyntaxKind.NullLiteralExpression) ||
                expression.IsKind(SyntaxKind.DefaultLiteralExpression);
        }

        if (declaration.AccessorList?.Accessors.Any(static accessor =>
                accessor.Body is not null ||
                accessor.ExpressionBody is not null) is not false)
        {
            return false;
        }

        if (declaration.Initializer is { Value: { } initializer })
        {
            return !property.IsStatic &&
                property.SetMethod is null &&
                IsPrimaryConstructorParameterSource(
                    initializer,
                    semanticModel) &&
                HasConstructorParameterAssignment(
                    property,
                    initializer,
                    compilation,
                    cancellationToken);
        }

        if (property.IsStatic ||
            property.SetMethod is not null)
        {
            return false;
        }

        return HasConstructorParameterAssignment(
            property,
            primaryInitializer: null,
            compilation,
            cancellationToken);
    }

    private static bool IsPrimaryConstructorParameterSource(
        ExpressionSyntax expression,
        SemanticModel semanticModel)
    {
        var parameter = FindConstructorParameterSource(
            semanticModel.GetOperation(expression));
        if (parameter is null ||
            FindBehavioralInterfaceDependency(
                parameter.Type) is null)
        {
            return false;
        }

        return parameter.DeclaringSyntaxReferences.Any(
            static syntaxReference =>
                syntaxReference.GetSyntax() is ParameterSyntax
                {
                    Parent.Parent: TypeDeclarationSyntax,
                });
    }

    private static bool IsPositionalRecordParameter(
        ParameterSyntax parameter) =>
        parameter.Parent?.Parent is RecordDeclarationSyntax;

    private static bool HasUnsafePrimaryConstructorParameterUsage(
        IParameterSymbol parameter,
        ParameterSyntax declaration,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        if (declaration.Parent?.Parent is not
            (ClassDeclarationSyntax or StructDeclarationSyntax))
        {
            return false;
        }

        foreach (var name in root.DescendantNodes().OfType<IdentifierNameSyntax>())
        {
            if (!SymbolEqualityComparer.Default.Equals(
                    semanticModel.GetSymbolInfo(name).Symbol,
                    parameter) ||
                IsPrimaryConstructorInitializationReference(name))
            {
                continue;
            }

            return true;
        }

        return false;
    }

    private static bool IsPrimaryConstructorInitializationReference(
        IdentifierNameSyntax name)
    {
        if (name.Ancestors().OfType<BaseTypeSyntax>().Any())
        {
            return true;
        }

        var initializer = name
            .Ancestors()
            .OfType<EqualsValueClauseSyntax>()
            .FirstOrDefault();
        return initializer?.Parent is VariableDeclaratorSyntax or
            PropertyDeclarationSyntax;
    }

    private static bool HasConstructorParameterAssignment(
        ISymbol target,
        ExpressionSyntax? primaryInitializer,
        Compilation compilation,
        CancellationToken cancellationToken)
    {
        var typeDeclarations = target.ContainingType
            .DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax(cancellationToken))
            .OfType<TypeDeclarationSyntax>()
            .ToArray();
        var constructors = typeDeclarations
            .SelectMany(static declaration => declaration.Members)
            .OfType<ConstructorDeclarationSyntax>()
            .ToArray();
        var primaryDeclarations = typeDeclarations
            .Where(static declaration =>
                declaration.ParameterList is not null)
            .ToArray();
        if (primaryDeclarations.Length > 1)
        {
            return false;
        }

        IMethodSymbol? primaryConstructor = null;
        if (primaryDeclarations.Length == 1)
        {
            primaryConstructor = FindPrimaryConstructor(
                primaryDeclarations[0],
                compilation,
                cancellationToken);
            if (primaryConstructor is null ||
                primaryInitializer is null ||
                !IsConstructorParameterValue(
                    compilation.GetSemanticModel(
                            primaryInitializer.SyntaxTree)
                        .GetOperation(
                            primaryInitializer,
                            cancellationToken),
                    primaryConstructor,
                    CreateRootParameterProvenance(
                        primaryConstructor)))
            {
                return false;
            }
        }
        else if (primaryInitializer is not null)
        {
            return false;
        }

        if (constructors.Length == 0)
        {
            return primaryConstructor is not null;
        }

        foreach (var declaration in constructors)
        {
            var semanticModel = compilation.GetSemanticModel(
                declaration.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(
                    declaration,
                    cancellationToken) is not
                    {
                        MethodKind: MethodKind.Constructor,
                    } constructor)
            {
                return false;
            }

            var result = AnalyzeConstructorParameterAssignment(
                target,
                declaration,
                constructor,
                CreateRootParameterProvenance(constructor),
                primaryInitializer,
                primaryConstructor,
                compilation,
                new HashSet<IMethodSymbol>(
                    SymbolEqualityComparer.Default),
                cancellationToken);
            if (result is false)
            {
                return false;
            }
        }

        return true;
    }

    private static IMethodSymbol? FindPrimaryConstructor(
        TypeDeclarationSyntax declaration,
        Compilation compilation,
        CancellationToken cancellationToken)
    {
        if (declaration.ParameterList is null)
        {
            return null;
        }

        var semanticModel = compilation.GetSemanticModel(
            declaration.SyntaxTree);
        foreach (var parameterSyntax in declaration.ParameterList.Parameters)
        {
            if (semanticModel.GetDeclaredSymbol(
                    parameterSyntax,
                    cancellationToken) is IParameterSymbol
                {
                    ContainingSymbol: IMethodSymbol
                    {
                        MethodKind: MethodKind.Constructor,
                    } constructor,
                })
            {
                return constructor;
            }
        }

        return null;
    }

    private static ImmutableArray<bool> CreateRootParameterProvenance(
        IMethodSymbol constructor) =>
        constructor.Parameters
            .Select(parameter =>
                FindBehavioralInterfaceDependency(parameter.Type) is not null)
            .ToImmutableArray();

    private static bool? AnalyzeConstructorParameterAssignment(
        ISymbol target,
        ConstructorDeclarationSyntax declaration,
        IMethodSymbol constructor,
        ImmutableArray<bool> parameterProvenance,
        ExpressionSyntax? primaryInitializer,
        IMethodSymbol? primaryConstructor,
        Compilation compilation,
        HashSet<IMethodSymbol> activeConstructors,
        CancellationToken cancellationToken)
    {
        var normalizedConstructor = constructor.OriginalDefinition;
        if (!activeConstructors.Add(normalizedConstructor))
        {
            return false;
        }

        try
        {
            bool? initialState = false;
            if (declaration.Initializer?.IsKind(
                    SyntaxKind.ThisConstructorInitializer) is true)
            {
                var semanticModel = compilation.GetSemanticModel(
                    declaration.SyntaxTree);
                var invocation = FindConstructorInitializerInvocation(
                    semanticModel.GetOperation(
                        declaration.Initializer,
                        cancellationToken));
                if (invocation is null)
                {
                    return false;
                }

                var delegatedConstructor = invocation.TargetMethod;
                var delegatedProvenance =
                    MapDelegatedConstructorParameters(
                        invocation,
                        constructor,
                        parameterProvenance);
                var delegatedDeclaration =
                    FindConstructorDeclaration(
                        delegatedConstructor,
                        cancellationToken);
                if (delegatedDeclaration is not null)
                {
                    initialState = AnalyzeConstructorParameterAssignment(
                        target,
                        delegatedDeclaration,
                        delegatedConstructor,
                        delegatedProvenance,
                        primaryInitializer,
                        primaryConstructor,
                        compilation,
                        activeConstructors,
                        cancellationToken);
                }
                else if (primaryConstructor is not null &&
                         SymbolEqualityComparer.Default.Equals(
                             delegatedConstructor.OriginalDefinition,
                             primaryConstructor.OriginalDefinition))
                {
                    initialState = IsPrimaryInitializerProvenanced(
                        primaryInitializer,
                        primaryConstructor,
                        delegatedProvenance,
                        compilation,
                        cancellationToken);
                }
                else
                {
                    initialState = false;
                }
            }

            return AnalyzeConstructorBodyAssignment(
                target,
                declaration,
                constructor,
                parameterProvenance,
                initialState,
                compilation.GetSemanticModel(declaration.SyntaxTree),
                cancellationToken);
        }
        finally
        {
            activeConstructors.Remove(normalizedConstructor);
        }
    }

    private static IInvocationOperation?
        FindConstructorInitializerInvocation(IOperation? operation)
    {
        if (operation is IInvocationOperation invocation)
        {
            return invocation;
        }

        if (operation is null)
        {
            return null;
        }

        foreach (var child in operation.ChildOperations)
        {
            var nested = FindConstructorInitializerInvocation(child);
            if (nested is not null)
            {
                return nested;
            }
        }

        return null;
    }

    private static ImmutableArray<bool> MapDelegatedConstructorParameters(
        IInvocationOperation invocation,
        IMethodSymbol currentConstructor,
        ImmutableArray<bool> currentProvenance)
    {
        var mapped = new bool[invocation.TargetMethod.Parameters.Length];
        var assigned = new bool[mapped.Length];
        foreach (var argument in invocation.Arguments)
        {
            if (argument.Parameter is not { } parameter ||
                parameter.Ordinal < 0 ||
                parameter.Ordinal >= mapped.Length)
            {
                continue;
            }

            var isProvenanced = IsConstructorParameterValue(
                argument.Value,
                currentConstructor,
                currentProvenance);
            mapped[parameter.Ordinal] = assigned[parameter.Ordinal]
                ? mapped[parameter.Ordinal] && isProvenanced
                : isProvenanced;
            assigned[parameter.Ordinal] = true;
        }

        return [.. mapped];
    }

    private static ConstructorDeclarationSyntax? FindConstructorDeclaration(
        IMethodSymbol constructor,
        CancellationToken cancellationToken) =>
        constructor
            .DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax(cancellationToken))
            .OfType<ConstructorDeclarationSyntax>()
            .FirstOrDefault();

    private static bool IsPrimaryInitializerProvenanced(
        ExpressionSyntax? initializer,
        IMethodSymbol primaryConstructor,
        ImmutableArray<bool> parameterProvenance,
        Compilation compilation,
        CancellationToken cancellationToken) =>
        initializer is not null &&
        IsConstructorParameterValue(
            compilation.GetSemanticModel(initializer.SyntaxTree)
                .GetOperation(initializer, cancellationToken),
            primaryConstructor,
            parameterProvenance);

    private static bool? AnalyzeConstructorBodyAssignment(
        ISymbol target,
        ConstructorDeclarationSyntax declaration,
        IMethodSymbol constructor,
        ImmutableArray<bool> parameterProvenance,
        bool? initialState,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        if (initialState is null)
        {
            return null;
        }

        if (semanticModel.GetOperation(
                declaration,
                cancellationToken) is not
            IConstructorBodyOperation constructorBody)
        {
            return false;
        }

        ControlFlowGraph graph;
        try
        {
            graph = ControlFlowGraph.Create(
                constructorBody,
                cancellationToken);
        }
        catch (ArgumentException)
        {
            return false;
        }
        catch (InvalidOperationException)
        {
            return false;
        }

        if (HasUnsupportedConstructorExceptionFlow(graph.Root))
        {
            return false;
        }

        var entry = graph.Blocks.FirstOrDefault(static block =>
            block.Kind == BasicBlockKind.Entry);
        var exit = graph.Blocks.FirstOrDefault(static block =>
            block.Kind == BasicBlockKind.Exit);
        if (entry is null || exit is null)
        {
            return false;
        }

        var inputs = new bool?[graph.Blocks.Length];
        var work = new Queue<int>();
        inputs[entry.Ordinal] = initialState.Value;
        work.Enqueue(entry.Ordinal);
        while (work.Count > 0)
        {
            var block = graph.Blocks[work.Dequeue()];
            var input = inputs[block.Ordinal];
            if (input is null || !block.IsReachable)
            {
                continue;
            }

            var output = input.Value;
            foreach (var operation in block.Operations)
            {
                output = ApplyConstructorAssignmentOperation(
                    output,
                    operation,
                    target,
                    constructor,
                    parameterProvenance,
                    semanticModel,
                    cancellationToken);
            }

            if (block.BranchValue is not null)
            {
                output = ApplyConstructorAssignmentOperation(
                    output,
                    block.BranchValue,
                    target,
                    constructor,
                    parameterProvenance,
                    semanticModel,
                    cancellationToken);
            }

            if (!PropagateConstructorAssignmentBranch(
                    block.FallThroughSuccessor,
                    block,
                    output,
                    inputs,
                    work) ||
                !PropagateConstructorAssignmentBranch(
                    block.ConditionalSuccessor,
                    block,
                    output,
                    inputs,
                    work))
            {
                return false;
            }
        }

        return inputs[exit.Ordinal];
    }

    private static bool HasUnsupportedConstructorExceptionFlow(
        ControlFlowRegion region)
    {
        if (region.Kind is
            ControlFlowRegionKind.Filter or
            ControlFlowRegionKind.Catch or
            ControlFlowRegionKind.FilterAndHandler or
            ControlFlowRegionKind.TryAndCatch or
            ControlFlowRegionKind.Finally or
            ControlFlowRegionKind.TryAndFinally)
        {
            return true;
        }

        return region.NestedRegions.Any(
            HasUnsupportedConstructorExceptionFlow);
    }

    private static bool PropagateConstructorAssignmentBranch(
        ControlFlowBranch? branch,
        BasicBlock source,
        bool output,
        bool?[] inputs,
        Queue<int> work)
    {
        if (branch is null ||
            branch.Semantics is
                ControlFlowBranchSemantics.Throw or
                ControlFlowBranchSemantics.Rethrow or
                ControlFlowBranchSemantics.ProgramTermination)
        {
            return true;
        }

        if (branch.Semantics is not
                (ControlFlowBranchSemantics.Regular or
                 ControlFlowBranchSemantics.Return) ||
            branch.FinallyRegions.Length > 0)
        {
            return false;
        }

        if (branch.Destination is not { IsReachable: true } destination ||
            !CanTakeConstructorAssignmentBranch(source, branch))
        {
            return true;
        }

        var prior = inputs[destination.Ordinal];
        var joined = prior is null
            ? output
            : prior.Value && output;
        if (prior != joined)
        {
            inputs[destination.Ordinal] = joined;
            work.Enqueue(destination.Ordinal);
        }

        return true;
    }

    private static bool CanTakeConstructorAssignmentBranch(
        BasicBlock source,
        ControlFlowBranch branch)
    {
        if (source.ConditionKind == ControlFlowConditionKind.None ||
            source.BranchValue is not { } branchValue ||
            !branchValue.ConstantValue.HasValue ||
            branchValue.ConstantValue.Value is not bool condition)
        {
            return true;
        }

        var takesConditionalSuccessor =
            source.ConditionKind == ControlFlowConditionKind.WhenTrue
                ? condition
                : !condition;
        return branch.IsConditionalSuccessor ==
            takesConditionalSuccessor;
    }

    private static bool ApplyConstructorAssignmentOperation(
        bool state,
        IOperation operation,
        ISymbol target,
        IMethodSymbol constructor,
        ImmutableArray<bool> parameterProvenance,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        if (operation is
            ILocalFunctionOperation or
            IAnonymousFunctionOperation or
            IFlowAnonymousFunctionOperation)
        {
            return state;
        }

        foreach (var child in operation.ChildOperations)
        {
            state = ApplyConstructorAssignmentOperation(
                state,
                child,
                target,
                constructor,
                parameterProvenance,
                semanticModel,
                cancellationToken);
        }

        if (operation is IAssignmentOperation assignment)
        {
            var originalAssignment = FindOriginalConstructorAssignment(
                assignment,
                semanticModel,
                cancellationToken);
            var effectiveAssignment =
                originalAssignment ?? assignment;
            if (ContainsConstructorDependencyTarget(
                    effectiveAssignment.Target,
                    target))
            {
                if (effectiveAssignment is not
                        ISimpleAssignmentOperation ||
                    !IsExactConstructorDependencyTarget(
                        effectiveAssignment.Target,
                        target))
                {
                    return false;
                }

                return IsConstructorParameterValue(
                    effectiveAssignment.Value,
                    constructor,
                    parameterProvenance);
            }
        }

        if (operation is IIncrementOrDecrementOperation increment &&
            ContainsConstructorDependencyTarget(
                increment.Target,
                target))
        {
            return false;
        }

        if (operation is IArgumentOperation
            {
                Parameter.RefKind: RefKind.Ref or RefKind.Out,
            } argument &&
            ContainsConstructorDependencyTarget(argument.Value, target))
        {
            return false;
        }

        return state;
    }

    private static IAssignmentOperation? FindOriginalConstructorAssignment(
        IAssignmentOperation assignment,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        foreach (var assignmentSyntax in assignment.Syntax
                     .AncestorsAndSelf()
                     .OfType<AssignmentExpressionSyntax>())
        {
            if (semanticModel.GetOperation(
                    assignmentSyntax,
                    cancellationToken) is
                IAssignmentOperation originalAssignment)
            {
                return originalAssignment;
            }
        }

        return null;
    }

    private static bool ContainsConstructorDependencyTarget(
        IOperation operation,
        ISymbol target)
    {
        if (IsExactConstructorDependencyTarget(operation, target))
        {
            return true;
        }

        foreach (var child in operation.ChildOperations)
        {
            if (ContainsConstructorDependencyTarget(child, target))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsExactConstructorDependencyTarget(
        IOperation operation,
        ISymbol target)
    {
        var referencedSymbol = operation switch
        {
            IFieldReferenceOperation fieldReference =>
                fieldReference.Field,
            IPropertyReferenceOperation propertyReference =>
                propertyReference.Property,
            IParenthesizedOperation parenthesized =>
                GetConstructorDependencyTargetSymbol(
                    parenthesized.Operand),
            _ => null,
        };
        return SymbolEqualityComparer.Default.Equals(
            referencedSymbol,
            target);
    }

    private static ISymbol? GetConstructorDependencyTargetSymbol(
        IOperation operation) =>
        operation switch
        {
            IFieldReferenceOperation fieldReference =>
                fieldReference.Field,
            IPropertyReferenceOperation propertyReference =>
                propertyReference.Property,
            IParenthesizedOperation parenthesized =>
                GetConstructorDependencyTargetSymbol(
                    parenthesized.Operand),
            _ => null,
        };

    private static bool IsConstructorParameterValue(
        IOperation? operation,
        IMethodSymbol constructor,
        ImmutableArray<bool> parameterProvenance) =>
        operation switch
        {
            IParameterReferenceOperation parameterReference =>
                SymbolEqualityComparer.Default.Equals(
                    parameterReference.Parameter.ContainingSymbol,
                    constructor) &&
                parameterReference.Parameter.Ordinal >= 0 &&
                parameterReference.Parameter.Ordinal <
                    parameterProvenance.Length &&
                parameterProvenance[
                    parameterReference.Parameter.Ordinal] &&
                FindBehavioralInterfaceDependency(
                    parameterReference.Parameter.Type) is not null,
            IConversionOperation
            {
                OperatorMethod: null,
            } conversion =>
                IsConstructorParameterValue(
                    conversion.Operand,
                    constructor,
                    parameterProvenance),
            IParenthesizedOperation parenthesized =>
                IsConstructorParameterValue(
                    parenthesized.Operand,
                    constructor,
                    parameterProvenance),
            ICoalesceOperation coalesce =>
                IsConstructorParameterValue(
                    coalesce.Value,
                    constructor,
                    parameterProvenance) &&
                IsConstructorParameterValue(
                    coalesce.WhenNull,
                    constructor,
                    parameterProvenance),
            IConditionalOperation conditional =>
                IsConstructorParameterValue(
                    conditional.WhenTrue,
                    constructor,
                    parameterProvenance) &&
                IsConstructorParameterValue(
                    conditional.WhenFalse,
                    constructor,
                    parameterProvenance),
            ISwitchExpressionOperation switchExpression =>
                switchExpression.Arms.Length > 0 &&
                switchExpression.Arms.All(arm =>
                    IsConstructorParameterValue(
                        arm.Value,
                        constructor,
                        parameterProvenance)),
            IThrowOperation => true,
            _ => false,
        };

    private static IParameterSymbol? FindConstructorParameterSource(
        IOperation? operation) =>
        operation switch
        {
            IParameterReferenceOperation parameterReference =>
                parameterReference.Parameter,
            IConversionOperation conversion =>
                FindConstructorParameterSource(conversion.Operand),
            IParenthesizedOperation parenthesized =>
                FindConstructorParameterSource(parenthesized.Operand),
            ICoalesceOperation coalesce =>
                FindConstructorParameterSource(coalesce.Value),
            _ => null,
        };

    private static INamedTypeSymbol? FindConcreteBehavioralDependency(
        ITypeSymbol type) =>
        FindBehavioralDependency(
            type,
            static namedType =>
                namedType.TypeKind == TypeKind.Class &&
                IsBehavioralServiceType(namedType),
            new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default),
            skipAsyncResultCarriers: true);

    private static INamedTypeSymbol? FindBehavioralInterfaceDependency(
        ITypeSymbol type) =>
        FindBehavioralDependency(
            type,
            static namedType =>
                namedType.TypeKind == TypeKind.Interface &&
                IsRelevantBehavioralInterfaceContract(namedType),
            new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default),
            skipAsyncResultCarriers: true);

    private static INamedTypeSymbol? FindBehavioralDependency(
        ITypeSymbol type,
        Func<INamedTypeSymbol, bool> isDependency,
        HashSet<ITypeSymbol> visited,
        bool skipAsyncResultCarriers = false)
    {
        if (!visited.Add(type))
        {
            return null;
        }

        if (type is IArrayTypeSymbol arrayType)
        {
            return FindBehavioralDependency(
                arrayType.ElementType,
                isDependency,
                visited,
                skipAsyncResultCarriers);
        }

        if (type is ITypeParameterSymbol typeParameter)
        {
            foreach (var constraint in typeParameter.ConstraintTypes)
            {
                var constrainedDependency = FindBehavioralDependency(
                    constraint,
                    isDependency,
                    visited,
                    skipAsyncResultCarriers);
                if (constrainedDependency is not null)
                {
                    return constrainedDependency;
                }
            }

            return null;
        }

        if (type is not INamedTypeSymbol namedType)
        {
            return null;
        }

        if (isDependency(namedType))
        {
            return namedType;
        }

        if (skipAsyncResultCarriers &&
            IsAsyncResultCarrier(namedType))
        {
            return null;
        }

        foreach (var typeArgument in namedType.TypeArguments)
        {
            var dependency = FindBehavioralDependency(
                typeArgument,
                isDependency,
                visited,
                skipAsyncResultCarriers);
            if (dependency is not null)
            {
                return dependency;
            }
        }

        return null;
    }

    private static bool IsAsyncResultCarrier(INamedTypeSymbol type) =>
        type.Arity == 1 &&
        type.ContainingNamespace
            .ToDisplayString()
            .Equals(
                "System.Threading.Tasks",
                StringComparison.Ordinal) &&
        type.Name is
            "Task" or
            "TaskCompletionSource" or
            "ValueTask";

    private static bool IsConstructorParameter(ParameterSyntax parameter) =>
        parameter.Parent?.Parent is ConstructorDeclarationSyntax or
            TypeDeclarationSyntax;

    private static void AnalyzeBehavioralServices(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        foreach (var declaration in root
                     .DescendantNodes()
                     .OfType<TypeDeclarationSyntax>())
        {
            if (semanticModel.GetDeclaredSymbol(
                    declaration,
                    context.CancellationToken) is not INamedTypeSymbol symbol ||
                symbol.TypeKind != TypeKind.Class ||
                symbol.IsStatic ||
                !IsBehavioralServiceType(symbol) ||
                HasFrameworkBehavioralBaseContract(symbol) ||
                HasRelevantBehavioralInterfaceContract(symbol))
            {
                continue;
            }

            context.ReportDiagnostic(
                Diagnostic.Create(
                    BehavioralServiceRequiresContract,
                    declaration.Identifier.GetLocation(),
                    symbol.Name));
        }
    }

    private static void AnalyzeBehavioralInterfaceReturns(
        SyntaxTreeAnalysisContext context,
        SemanticModel semanticModel,
        SyntaxNode root)
    {
        foreach (var interfaceDeclaration in root
                     .DescendantNodes()
                     .OfType<InterfaceDeclarationSyntax>())
        {
            if (semanticModel.GetDeclaredSymbol(
                    interfaceDeclaration,
                    context.CancellationToken) is not
                    INamedTypeSymbol interfaceSymbol)
            {
                continue;
            }

            var observedMembers = new HashSet<string>(StringComparer.Ordinal);
            INamedTypeSymbol[] declaredInterface = [interfaceSymbol];
            foreach (var declaringInterface in declaredInterface.Concat(
                         interfaceSymbol.AllInterfaces))
            {
                foreach (var member in declaringInterface.GetMembers())
                {
                    var returnType = member switch
                    {
                        IMethodSymbol
                        {
                            MethodKind: MethodKind.Ordinary,
                        } method => method.ReturnType,
                        IPropertySymbol property => property.Type,
                        _ => null,
                    };
                    var memberKey = member.ToDisplayString(
                        SymbolDisplayFormat.FullyQualifiedFormat);
                    if (returnType is null ||
                        !observedMembers.Add(memberKey))
                    {
                        continue;
                    }

                    ReportConcreteBehavioralInterfaceReturn(
                        context,
                        member,
                        returnType,
                        interfaceDeclaration.Identifier.GetLocation());
                }
            }
        }
    }

    private static void ReportConcreteBehavioralInterfaceReturn(
        SyntaxTreeAnalysisContext context,
        ISymbol member,
        ITypeSymbol returnType,
        Location location)
    {
        var concreteReturn = FindConcreteBehavioralReturn(returnType);
        if (concreteReturn is null)
        {
            return;
        }

        context.ReportDiagnostic(
            Diagnostic.Create(
                ConcreteBehavioralInterfaceReturn,
                location,
                member.ToDisplayString(
                    SymbolDisplayFormat.CSharpErrorMessageFormat),
                concreteReturn.ToDisplayString(
                    SymbolDisplayFormat.CSharpErrorMessageFormat)));
    }

    private static INamedTypeSymbol? FindConcreteBehavioralReturn(
        ITypeSymbol returnType) =>
        FindBehavioralDependency(
            returnType,
            static namedType =>
                namedType.TypeKind == TypeKind.Class &&
                !IsFrameworkType(namedType) &&
                !IsImmutableValueContract(namedType) &&
                HasSubstitutableInterfaceContract(namedType),
            new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default));

    private static bool IsImmutableValueContract(INamedTypeSymbol type)
    {
        string[] immutableSuffixes =
        [
            "Contract",
            "Definition",
            "Descriptor",
            "Reference",
            "Request",
            "Response",
            "Result",
            "Value",
        ];
        if (type.AllInterfaces.Any(IsRelevantBehavioralInterfaceContract) ||
            !type.IsSealed ||
            HasBehavioralSuffix(type.Name) ||
            (!type.IsRecord &&
             !immutableSuffixes.Any(suffix =>
                 type.Name.EndsWith(suffix, StringComparison.Ordinal))))
        {
            return false;
        }

        return type.GetMembers().All(static member =>
            member switch
            {
                IFieldSymbol field =>
                    field.IsStatic || field.IsReadOnly || field.IsConst,
                IPropertySymbol property =>
                    property.IsStatic ||
                    property.SetMethod is null ||
                    property.SetMethod.IsInitOnly,
                IEventSymbol @event => @event.IsStatic,
                IMethodSymbol method =>
                    method.IsImplicitlyDeclared ||
                    method.IsStatic ||
                    method.MethodKind is not MethodKind.Ordinary ||
                    OverridesSystemObjectMethod(method),
                _ => true,
            });
    }

    private static bool IsBehavioralServiceType(INamedTypeSymbol type)
    {
        if (IsFrameworkType(type))
        {
            return false;
        }

        if (HasBehavioralSuffix(type.Name))
        {
            return !HasFrameworkBehavioralBaseContract(type);
        }

        return type.AllInterfaces.Any(
            IsRelevantBehavioralInterfaceContract);
    }

    private static bool HasBehavioralSuffix(string name) =>
        BehavioralServiceSuffixes.Any(suffix =>
            name.EndsWith(suffix, StringComparison.Ordinal));

    private static bool HasFrameworkBehavioralBaseContract(
        INamedTypeSymbol type)
    {
        var hasFrameworkContract = false;
        for (var baseType = type.BaseType;
             baseType is not null;
             baseType = baseType.BaseType)
        {
            if (IsFrameworkType(baseType) &&
                baseType.IsAbstract &&
                GetInstanceBehaviorMembers(baseType).Any(static member =>
                    member.IsAbstract))
            {
                hasFrameworkContract = true;
                break;
            }
        }

        return hasFrameworkContract &&
            GetEffectivePublicInstanceBehaviorMembers(type)
                .All(OverridesFrameworkMember);
    }

    private static bool OverridesFrameworkMember(ISymbol member)
    {
        ISymbol? overriddenMember = member switch
        {
            IMethodSymbol method => method.OverriddenMethod,
            IPropertySymbol property => property.OverriddenProperty,
            IEventSymbol @event => @event.OverriddenEvent,
            _ => null,
        };
        return WalkOverriddenMembers(overriddenMember)
            .Any(overridden =>
                IsFrameworkType(overridden.ContainingType));
    }

    private static bool HasRelevantBehavioralInterfaceContract(
        INamedTypeSymbol type) =>
        HasCompleteInterfaceContract(
            type,
            IsRelevantBehavioralInterfaceContract);

    private static bool IsRelevantBehavioralInterfaceContract(
        INamedTypeSymbol @interface)
    {
        if (!HasInterfaceBehavior(@interface))
        {
            return false;
        }

        if (HasBehavioralSuffix(@interface.Name))
        {
            return true;
        }

        return !IsFrameworkType(@interface) &&
            HasCallableInterfaceBehavior(@interface);
    }

    private static bool HasCallableInterfaceBehavior(
        INamedTypeSymbol @interface) =>
        @interface.GetMembers().Any(IsCallableInterfaceBehaviorMember) ||
        @interface.AllInterfaces.Any(inherited =>
            inherited.GetMembers().Any(IsCallableInterfaceBehaviorMember));

    private static bool IsCallableInterfaceBehaviorMember(ISymbol member) =>
        member switch
        {
            IEventSymbol => true,
            IMethodSymbol method =>
                !method.IsStatic &&
                method.MethodKind == MethodKind.Ordinary,
            _ => false,
        };

    private static bool HasSubstitutableInterfaceContract(
        INamedTypeSymbol type) =>
        HasCompleteInterfaceContract(
            type,
            static @interface =>
                !IsFrameworkMarkerInterface(@interface) &&
                HasInterfaceBehavior(@interface));

    private static bool HasCompleteInterfaceContract(
        INamedTypeSymbol type,
        Func<INamedTypeSymbol, bool> isQualifyingInterface)
    {
        var interfaces = type.AllInterfaces
            .Where(HasInterfaceBehavior)
            .ToImmutableArray();
        if (!interfaces
                .Where(isQualifyingInterface)
                .SelectMany(GetInstanceBehaviorMembers)
                .Any(member =>
                    type.FindImplementationForInterfaceMember(member) is not
                        null))
        {
            return false;
        }

        var contractedImplementations = interfaces
            .SelectMany(GetInstanceBehaviorMembers)
            .Select(type.FindImplementationForInterfaceMember)
            .OfType<ISymbol>()
            .ToImmutableHashSet(SymbolEqualityComparer.Default);
        return GetEffectivePublicInstanceBehaviorMembers(type)
            .All(contractedImplementations.Contains);
    }

    private static bool HasInterfaceBehavior(INamedTypeSymbol @interface) =>
        DeclaresBehavior(@interface) ||
        @interface.AllInterfaces.Any(DeclaresBehavior);

    private static bool DeclaresBehavior(INamedTypeSymbol @interface) =>
        GetInstanceBehaviorMembers(@interface).Any();

    private static IEnumerable<ISymbol> GetInstanceBehaviorMembers(
        INamedTypeSymbol type) =>
        type.GetMembers().Where(IsInstanceBehaviorMember);

    private static List<ISymbol>
        GetEffectivePublicInstanceBehaviorMembers(INamedTypeSymbol type)
    {
        var effectiveMembers = new List<ISymbol>();
        for (INamedTypeSymbol? current = type;
             current is not null && !IsFrameworkType(current);
             current = current.BaseType)
        {
            foreach (var member in current
                         .GetMembers()
                         .Where(IsPublicInstanceBehaviorMember)
                         .Where(static member =>
                             !IsAmbientGeneratedImplementationMember(member)))
            {
                if (effectiveMembers.Any(existing =>
                        OverridesMember(existing, member)))
                {
                    continue;
                }

                effectiveMembers.Add(member);
            }
        }

        return effectiveMembers;
    }

    private static bool IsAmbientGeneratedImplementationMember(
        ISymbol member)
    {
        var declarations = member.DeclaringSyntaxReferences;
        return declarations.Length > 0 &&
            declarations.All(static reference =>
            {
                var sourcePath = reference.SyntaxTree.FilePath;
                if (string.IsNullOrWhiteSpace(sourcePath))
                {
                    return true;
                }

                var normalizedPath = NormalizePath(sourcePath);
                if (FindPathSegment(
                        normalizedPath,
                        GeneratedSourceMarker) >= 0)
                {
                    return false;
                }

                var sourceText = reference.SyntaxTree.GetText();
                if (HasExactGeneratedSourceOwnershipHeader(sourceText))
                {
                    return false;
                }

                if (HasAutoGeneratedLeadingClaim(
                        sourceText,
                        reference.SyntaxTree.GetRoot()))
                {
                    return true;
                }

                if (!Path.IsPathRooted(sourcePath))
                {
                    return true;
                }

                return normalizedPath.Contains(
                    "/obj/ProgramKitCompilerGenerated/",
                    StringComparison.OrdinalIgnoreCase);
            });
    }

    private static bool IsPublicInstanceBehaviorMember(ISymbol member)
    {
        if (member.DeclaredAccessibility != Accessibility.Public ||
            member.IsImplicitlyDeclared ||
            !IsInstanceBehaviorMember(member))
        {
            return false;
        }

        return member is not IMethodSymbol method ||
            !OverridesSystemObjectMethod(method);
    }

    private static bool OverridesMember(
        ISymbol possibleOverride,
        ISymbol baseMember) =>
        possibleOverride switch
        {
            IMethodSymbol method =>
                WalkOverriddenMembers(method.OverriddenMethod)
                    .Contains(baseMember, SymbolEqualityComparer.Default),
            IPropertySymbol property =>
                WalkOverriddenMembers(property.OverriddenProperty)
                    .Contains(baseMember, SymbolEqualityComparer.Default),
            IEventSymbol @event =>
                WalkOverriddenMembers(@event.OverriddenEvent)
                    .Contains(baseMember, SymbolEqualityComparer.Default),
            _ => false,
        };

    private static IEnumerable<ISymbol> WalkOverriddenMembers(
        ISymbol? member)
    {
        while (member is not null)
        {
            yield return member;
            member = member switch
            {
                IMethodSymbol method => method.OverriddenMethod,
                IPropertySymbol property => property.OverriddenProperty,
                IEventSymbol @event => @event.OverriddenEvent,
                _ => null,
            };
        }
    }

    private static bool OverridesSystemObjectMethod(IMethodSymbol method) =>
        WalkOverriddenMembers(method.OverriddenMethod)
            .OfType<IMethodSymbol>()
            .Any(overridden =>
                overridden.ContainingType.SpecialType ==
                    SpecialType.System_Object);

    private static bool IsInstanceBehaviorMember(ISymbol member) =>
        member switch
        {
            IPropertySymbol property => !property.IsStatic,
            IEventSymbol @event => !@event.IsStatic,
            IMethodSymbol method => !method.IsStatic &&
                method.MethodKind == MethodKind.Ordinary,
            _ => false,
        };

    private static bool IsFrameworkType(INamedTypeSymbol type)
    {
        var namespaceName = type.ContainingNamespace.ToDisplayString();
        return namespaceName.Equals("System", StringComparison.Ordinal) ||
            namespaceName.StartsWith("System.", StringComparison.Ordinal) ||
            namespaceName.Equals("Microsoft", StringComparison.Ordinal) ||
            namespaceName.StartsWith("Microsoft.", StringComparison.Ordinal);
    }

    private static bool IsFrameworkMarkerInterface(
        INamedTypeSymbol @interface)
    {
        if (!@interface.ContainingNamespace
                .ToDisplayString()
                .StartsWith("System", StringComparison.Ordinal))
        {
            return false;
        }

        return @interface.Name is
            "IDisposable" or
            "IAsyncDisposable" or
            "ICloneable" or
            "IComparable" or
            "IEquatable";
    }

    private static bool TryResolveSourceIdentity(
        SyntaxTreeAnalysisContext context,
        string? projectDirectory,
        bool claimsProgramKitGeneratedOwnership,
        bool claimsGeneratedCode,
        out string relativeSourcePath,
        out string ledgerSourcePath,
        out bool isAmbientGenerated)
    {
        relativeSourcePath = string.Empty;
        ledgerSourcePath = string.Empty;
        isAmbientGenerated = false;
        var sourcePath = context.Tree.FilePath;

        if (string.IsNullOrWhiteSpace(sourcePath))
        {
            if (claimsProgramKitGeneratedOwnership)
            {
                ReportGeneratedConvention(context, "<pathless>");
                return false;
            }

            isAmbientGenerated = true;
            return true;
        }

        var sourcePathIsRooted = Path.IsPathRooted(sourcePath);
        string? projectRelativeSourcePath = null;
        if (sourcePathIsRooted && projectDirectory is not null)
        {
            projectRelativeSourcePath = Path.GetRelativePath(
                Path.GetFullPath(projectDirectory),
                Path.GetFullPath(sourcePath));
        }

        var markerSearchPath = projectRelativeSourcePath is null
            ? NormalizePath(sourcePath)
            : NormalizePath(projectRelativeSourcePath);
        var generatedMarkerIndex = FindPathSegment(
            markerSearchPath,
            GeneratedSourceMarker);
        if (generatedMarkerIndex >= 0)
        {
            if (!claimsProgramKitGeneratedOwnership)
            {
                ReportGeneratedConvention(context, sourcePath);
                return false;
            }

            var logicalStart =
                generatedMarkerIndex + GeneratedSourceMarker.Length + 1;
            if (logicalStart >= markerSearchPath.Length)
            {
                ReportGeneratedConvention(context, sourcePath);
                return false;
            }

            var logicalSourcePath = markerSearchPath[logicalStart..];
            var logicalSegments = logicalSourcePath.Split('/');
            if (logicalSegments.Length != 2 ||
                logicalSegments.Any(string.IsNullOrWhiteSpace) ||
                logicalSegments.Any(segment =>
                    segment is "." or "..") ||
                !logicalSegments[1].EndsWith(
                    ".cs",
                    StringComparison.Ordinal) ||
                logicalSegments[1].Length == ".cs".Length)
            {
                ReportGeneratedConvention(context, sourcePath);
                return false;
            }

            relativeSourcePath = logicalSourcePath.Replace(
                '/',
                Path.DirectorySeparatorChar);
            ledgerSourcePath =
                $"{GeneratedSourceMarker}/{NormalizePath(relativeSourcePath)}";
            isAmbientGenerated = false;
            return true;
        }

        if (!sourcePathIsRooted)
        {
            if (claimsProgramKitGeneratedOwnership ||
                ClaimsProgramKitGeneratorProvenance(sourcePath))
            {
                ReportGeneratedConvention(context, sourcePath);
                return false;
            }

            isAmbientGenerated = true;
            return true;
        }

        if (projectDirectory is null)
        {
            return false;
        }

        relativeSourcePath = projectRelativeSourcePath!;
        ledgerSourcePath = NormalizePath(relativeSourcePath);

        if (IsOutsideProject(relativeSourcePath))
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    IntentFolderRequired,
                    context.Tree.GetRoot(context.CancellationToken).GetLocation(),
                    GetDisplayFileName(sourcePath),
                    "outside the project"));
            return false;
        }

        var firstSegment = SplitPath(relativeSourcePath).FirstOrDefault();
        if (string.Equals(
                firstSegment,
                "obj",
                StringComparison.OrdinalIgnoreCase) ||
            string.Equals(
                firstSegment,
                "bin",
                StringComparison.OrdinalIgnoreCase))
        {
            if (claimsProgramKitGeneratedOwnership ||
                ClaimsProgramKitGeneratorProvenance(relativeSourcePath))
            {
                ReportGeneratedConvention(context, sourcePath);
                return false;
            }

            isAmbientGenerated = true;
            return true;
        }

        if (claimsGeneratedCode ||
            ClaimsProgramKitGeneratorProvenance(relativeSourcePath))
        {
            ReportGeneratedConvention(context, sourcePath);
            return false;
        }

        return true;
    }

    private static bool HasGeneratedCodeClaim(
        SourceText sourceText,
        SyntaxNode root,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        if (HasAutoGeneratedLeadingClaim(sourceText, root))
        {
            return true;
        }

        foreach (var attribute in root
                     .DescendantNodes()
                     .OfType<AttributeSyntax>())
        {
            var constructor = semanticModel.GetSymbolInfo(
                    attribute,
                    cancellationToken)
                .Symbol as IMethodSymbol;
            var attributeType = constructor?.ContainingType;
            if (attributeType is null)
            {
                continue;
            }

            var metadataName = attributeType.ToDisplayString();
            if (metadataName is
                "System.CodeDom.Compiler.GeneratedCodeAttribute" or
                "System.Runtime.CompilerServices.CompilerGeneratedAttribute")
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAutoGeneratedLeadingClaim(
        SourceText sourceText,
        SyntaxNode root)
    {
        var firstToken = root.GetFirstToken(includeZeroWidth: true);
        var leadingLength = firstToken.RawKind == 0
            ? sourceText.Length
            : firstToken.SpanStart;
        var leadingText = leadingLength > 0
            ? sourceText.ToString(TextSpan.FromBounds(0, leadingLength))
            : string.Empty;
        if (leadingText.Contains(
                "<auto-generated",
                StringComparison.OrdinalIgnoreCase) ||
            leadingText.Contains(
                "<autogenerated",
