"""Materialize standalone consumer helpers from their stack-neutral source owner."""
from __future__ import annotations

import argparse
from pathlib import Path

FILES = ('device_toolchain.py', 'js_toolchain.py', 'owned_scratch.py',
         'python_runtime_contract.py', 'test_results.py')
SOURCE = Path('extensions/program-kit-governance/scripts/program_kit_runtime')
TARGET = Path('extensions/program-kit-dotnet/templates/dotnet/files/eng')
HEADER = '# Generated by scripts/sync_shared_runtime.py; edit program-kit-governance/scripts/program_kit_runtime instead.\n'


def sync(root: Path, *, check: bool = True) -> list[str]:
    changed = []
    for name in FILES:
        source, target = root / SOURCE / name, root / TARGET / name
        # Git checkouts can use LF or CRLF. Compare the generated text contract
        # under that native checkout transformation; all other edits still fail.
        expected = HEADER.encode() + source.read_bytes().replace(b'\r\n', b'\n')
        if not target.is_file() or target.read_bytes().replace(b'\r\n', b'\n') != expected:
            changed.append(name)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)
    if check and changed:
        raise ValueError('Shared consumer runtime differs from its canonical owner: '
                         + ', '.join(changed) + '; run python scripts/sync_shared_runtime.py --write')
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate the tracked standalone consumer copies.')
    args = parser.parse_args()
    changed = sync(Path(__file__).resolve().parents[1], check=not args.write)
    print('Shared runtime: ' + (', '.join(changed) if changed else 'canonical copies match'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
